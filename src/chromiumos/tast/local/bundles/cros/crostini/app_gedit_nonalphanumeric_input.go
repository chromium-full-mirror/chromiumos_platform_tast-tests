func AppGeditNonalphanumericInput(ctx context.Context, s *testing.State) {
	tconn := s.FixtValue().(crostini.FixtureData).Tconn
	keyboard := s.FixtValue().(crostini.FixtureData).KB

	// Reserve time for clean-up tasks.
	cleanupCtx := ctx
	ctx, cancel := ctxutil.Shorten(ctx, 15*time.Second)
	defer cancel()

	// Open Terminal app.
	terminalApp, err := terminalapp.Launch(ctx, tconn)
	if err != nil {
		s.Fatal("Failed to open Terminal app: ", err)
	}
	defer terminalApp.Exit(keyboard)(cleanupCtx)

	defer faillog.DumpUITreeOnError(cleanupCtx, s.OutDir(), s.HasError, tconn)

	const testFile = "test.txt"

	ui := uiauto.New(tconn)
	uda := uidetection.NewDefault(tconn)
	appWindow := nodewith.NameStartingWith(testFile).Role(role.Window).First()

	if err := uiauto.Combine("Open file with Gedit via the terminal",
		// Launch Gedit.
		terminalApp.RunCommand(keyboard, "gedit "+testFile),
		// Sometimes the first character gets lost if input is entered immediately.
		// Wait until the menu exists, indicating the window is launched.
		uda.WaitUntilExists(uidetection.Word("Open").WithinA11yNode(appWindow)),
		ui.LeftClick(appWindow),
	)(ctx); err != nil {
		s.Fatal("Failed to open gedit: ", err)
	}

	if err := typeAndEditString(ctx, keyboard, tconn); err != nil {
		s.Fatal("Failed to type and edit string: ", err)
	}

	if err := uiauto.Combine("Close gedit",
		// Save the file.
		keyboard.AccelAction("ctrl+S"),
		// Press ctrl+W twice to exit window.
		keyboard.AccelAction("ctrl+W"),
		keyboard.AccelAction("ctrl+W"),
		// Check window close.
		ui.WaitUntilGone(appWindow),
	)(ctx); err != nil {
		s.Fatal("Failed to open file in gedit: ", err)
	}
}

func typeAndEditString(ctx context.Context, keyboard *input.KeyboardEventWriter, tconn *chrome.TestConn) error {
	// Switch to EnglishUS IME
	if err := ime.EnglishUS.InstallAndActivate(tconn)(ctx); err != nil {
		return err
	}

	const initialString = "Hi\nThis is a test."
	inputActions := []struct {
		actions        uiauto.Action
		expectedString string
	}{
		{uiauto.Combine("Type the initial 2-line string",
			keyboard.TypeAction(initialString),
		),
			initialString,
		},
		{uiauto.Combine("Go left and delete one character",
			// Hi\nThis is a test|.
			keyboard.AccelAction("Left"),
			keyboard.AccelAction("Backspace"),
		),
			"Hi\nThis is a tes.",
		},
		{uiauto.Combine("Go left and delete multiple characters",
			// Hi\nThis is a |tes.|
			keyboard.AccelAction("Shift+Left"),
			keyboard.AccelAction("Shift+Left"),
			keyboard.AccelAction("Shift+Left"),
			keyboard.AccelAction("Shift+Left"),
			// Hi\nThis is a |
			keyboard.AccelAction("Backspace"),
		),
			"Hi\nThis is a ",
		},
		{uiauto.Combine("Use arrow keys to copy the first line of string, then go up and paste",
			// |Hi\nThis is a
			keyboard.AccelAction("Ctrl+A"),
			keyboard.AccelAction("Left"),
			// |Hi\n|This is a
			keyboard.AccelAction("Shift+Down"),
			// |Hi\nThis is a
			keyboard.AccelAction("Ctrl+C"),
			keyboard.AccelAction("Up"),
			// Hi\nHi\n|This is a
			keyboard.AccelAction("Ctrl+V"),
		),
			"Hi\nHi\nThis is a ",
		},
		{uiauto.Combine("Enter and Tab keys",
			// Hi\nHi|\nThis is a
			keyboard.AccelAction("Shift+Up"),
			keyboard.AccelAction("Left"),
			// Hi\nHi\n\t|\nThis is a
			keyboard.AccelAction("Enter"),
			keyboard.AccelAction("Tab"),
		),
			"Hi\nHi\n\t\nThis is a ",
		},
	}

	for _, inputAction := range inputActions {
		testing.ContextLogf(ctx, "Typing %q", inputAction.expectedString)
		if err := inputAction.actions(ctx); err != nil {
			return errors.Wrap(err, "failed to complete keyboard action ")
		}
		if err := crostiniapps.CheckInputViaClipboard(ctx, keyboard, tconn, inputAction.expectedString); err != nil {
			return errors.Wrap(err, "failed to check current text")
		}
	}

	return nil
}
