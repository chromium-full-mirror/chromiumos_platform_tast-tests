func AppMaximizeRestoreMinimizeClose(ctx context.Context, s *testing.State) {
	tconn := s.FixtValue().(crostini.FixtureData).Tconn
	cr := s.FixtValue().(crostini.FixtureData).Chrome
	keyboard := s.FixtValue().(crostini.FixtureData).KB
	d := s.FixtValue().(crostini.FixtureData).Differ()
	cont := s.FixtValue().(crostini.FixtureData).Cont

	// Anything animated like blinking cursors will break screendiffs.
	cont.WriteFile(ctx, "~/.emacs", "(blink-cursor-mode 0)")
	cont.WriteFile(ctx, ".config/Code/User/settings.json", `{"editor.cursorBlinking": "solid","workbench.startupEditor": "None", "update.mode": "none"}`)

	appParams := []struct {
		// App name in the launcher and the shelf.
		appName string
		// App window name in the a11y tree.
		appWindowName string
		// Any word in the app to indicate the app is rendered onscreen.
		// E.g., "Files" in the menu of VS Code.
		wordInApp string
	}{
		{"Emacs (GUI)", "emacs@penguin", "Files"},
		{"Visual Studio Code", "Visual Studio Code", "Files"},
		// TODO(b/205650026) Maximize button is missing in Firefox-ESR and
		// Audacity, add these two apps once the issue is fixed.
	}

	for _, appParam := range appParams {
		uda := uidetection.NewDefault(tconn).WithTimeout(time.Minute)
		ui := uiauto.New(tconn)
		appWindow := nodewith.NameRegex(regexp.MustCompile(appParam.appWindowName)).Role(role.Window).First()
		shelf := nodewith.Name("Shelf").Role(role.Toolbar).HasClass("ShelfView")

		windowControlActions := []struct {
			name    string
			actions uiauto.Action
		}{
			{"maximize", uiauto.Combine("launch app and perform maximize/restore/close actions",
				launcher.SearchAndLaunchWithQuery(tconn, keyboard, appParam.appName, appParam.appName),
				// Wait until the window is stable.
				uda.WaitUntilExists(uidetection.Word(appParam.wordInApp).First().WithinA11yNode(appWindow)),
				crostini.Maximize(tconn, appWindow),
				d.DiffWindow(ctx, fmt.Sprintf("%s_maximized", appParam.appName), screenshot.Retries(3), screenshot.SkipSetWindowState(true)),
				crostini.RestoreFromMaximize(tconn, appWindow),
				d.DiffWindow(ctx, fmt.Sprintf("%s_restored", appParam.appName), screenshot.Retries(3), screenshot.SkipSetWindowState(true)),
				crostini.Close(tconn, appWindow),
				// Check the app disappears from the shelf.
				ui.WithTimeout(5*time.Second).WaitUntilGone(nodewith.NameContaining(appParam.appName).Role(role.Button).Visible().Ancestor(shelf)),
			)},
			{"minimize", uiauto.Combine("launch app and perform minimize/restore/close actions",
				launcher.SearchAndLaunchWithQuery(tconn, keyboard, appParam.appName, appParam.appName),
				// Wait until the window is stable.
				uda.WaitUntilExists(uidetection.Word(appParam.wordInApp).First().WithinA11yNode(appWindow)),
				crostini.Minimize(tconn, appWindow),
				// Check that the app is still on the shelf.
				ui.Exists(nodewith.NameContaining(appParam.appName).Role(role.Button).Visible().Ancestor(shelf)),
				crostini.ShowFromShelf(tconn, appWindow, appParam.appName),
				crostini.Close(tconn, appWindow),
				// Check the app disappears from the shelf.
				ui.WithTimeout(5*time.Second).WaitUntilGone(nodewith.NameContaining(appParam.appName).Role(role.Button).Visible().Ancestor(shelf)),
			)},
		}

		for _, windowControlAction := range windowControlActions {
			s.Run(ctx, fmt.Sprintf("%s_%s", appParam.appName, windowControlAction.name),
				func(ctx context.Context, s *testing.State) {
					cleanupCtx := ctx
					ctx, cancel := ctxutil.Shorten(ctx, 5*time.Second)
					defer cancel()
					defer faillog.DumpUITreeWithScreenshotOnError(cleanupCtx, s.OutDir(), s.HasError, cr, "ui_tree")

					if err := windowControlAction.actions(ctx); err != nil {
						s.Errorf("Failed to %s the app %s: %s", windowControlAction.name, appParam.appName, err)
					}
				})

		}
	}
}
