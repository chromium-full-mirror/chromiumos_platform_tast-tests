// prepareBeforePowerwash downloads the stateful image from Google cloud storage.
func prepareBeforePowerwash(ctx context.Context, cloudStorage *testing.CloudStorage) ([]byte, error) {
	testing.ContextLog(ctx, "Downloading stateful image")
	var statefulImage []byte
	if err := testing.Poll(ctx, func(ctx context.Context) error {
		statefulReader, err := cloudStorage.Open(ctx, "build-artifact:///stateful.tgz")
		if err != nil {
			return errors.Wrap(err, "failed to request stateful image from cloud storage")
		}
		defer statefulReader.Close()
		statefulImage, err = io.ReadAll(statefulReader)
		if err != nil {
			return errors.Wrap(err, "failed to read stateful image into buffer")
		}
		return nil
	}, &testing.PollOptions{Timeout: time.Minute}); err != nil {
		return nil, errors.Wrap(err, "failed to download stateful image")
	}
	return statefulImage, nil
}

// restoreAfterPowerwash restores the stateful partition from a provided image and Tast executables.
func restoreAfterPowerwash(ctx context.Context, statefulImage []byte, dut *dut.DUT, pushedFiles map[string]string) error {
	// Restore stateful partition from the image and trigger postinstall steps.
	testing.ContextLog(ctx, "Flashing stateful")
	flashCmd := dut.Conn().CommandContext(
		ctx, "/bin/tar", "--ignore-command-error", "--overwrite", "--directory",
		"/mnt/stateful_partition", "--selinux", "-xz")
	flashCmd.Stdin = bytes.NewReader(statefulImage)
	if err := flashCmd.Run(ssh.DumpLogOnError); err != nil {
		return errors.Wrap(err, "failed to flash stateful partition")
	}
	if err := linuxssh.WriteFile(ctx, dut.Conn(), "/mnt/stateful_partition/.update_available", []byte("clobber"), 0644); err != nil {
		return errors.Wrap(err, "failed to trigger postinstall steps")
	}
	if err := dut.Reboot(ctx); err != nil {
		return errors.Wrap(err, "failed to reboot after flashing stateful")
	}

	if len(pushedFiles) == 0 {
		return nil
	}

	// Push Tast executables to the DUT.
	testing.ContextLog(ctx, "Pushing executables to target")
	if _, err := linuxssh.PutFiles(ctx, dut.Conn(), pushedFiles, linuxssh.DereferenceSymlinks); err != nil {
		return errors.Wrap(err, "failed to push Tast executables")
	}

	if err := EnsureTPMAndSystemStateAreResetRemote(ctx, dut); err != nil {
		return errors.Wrap(err, "failed to reset TPM")
	}

	return nil
}

// PowerwashFunc represents a function that performs a powerwash.
type PowerwashFunc func(ctx context.Context) error

// Powerwash performs a powerwash on the DUT, restores the stateful partition from a provided image,
// and optionally runs a custom powerwash function.
//
//   - ctx is the test context.
//   - cloudStorage is a testing.CloudStorage instance, typically accessed via s.CloudStorage()
//     in a test.
//   - dut is a DUT instance, typically accessed via s.DUT() in a test.
//   - pushedFiles is a map from source file paths on the host to destination file paths on the DUT,
//     as would be passed to linuxssh.PutFiles. Typically this is generated by s.PushedFilesToDUT(<role>)
//     in a test, where <role> is the role of the DUT. The role for primary DUT is "", the roles for companion DUTs are cd1, cd2, ..cdN.
//   - powerwashFn is an optional function that will be executed after preparing for powerwash
//     but before restoring the stateful partition. This allows for custom powerwash triggers or actions.
//     The caller is responsible for making sure that the powerwash is finished and the DUT is connected.
//     If nil, the default manual powerwash mechanism is used.
//
// Example for primary DUT powerwash with default mechanism:
//
//	if err := policyutil.Powerwash(ctx, s.CloudStorage(), s.DUT(), s.PushedFilesToDUT(""), nil); err != nil {
//		s.Fatal("Powerwash failed: ", err)
//	}
//
// Example for primary DUT powerwash with a custom powerwash function:
//
//	customPowerwash := func(ctx context.Context) error {
//		// Your custom powerwash logic here, e.g., triggering powerwash via a remote command.
//		// Make sure that the powerwash finished and the DUT is connected.
//		return nil
//	}
//	if err := policyutil.Powerwash(ctx, s.CloudStorage(), s.DUT(), s.PushedFilesToDUT(""), customPowerwash); err != nil {
//		s.Fatal("Powerwash failed: ", err)
//	}
func Powerwash(ctx context.Context, cloudStorage *testing.CloudStorage, dut *dut.DUT, pushedFiles map[string]string, powerwashFn PowerwashFunc) (retErr error) {
	statefulImage, err := prepareBeforePowerwash(ctx, cloudStorage)
	if err != nil {
		return errors.Wrap(err, "failed to prepare to powerwash")
	}

	// Store logs before powerwash.
	log.Collect(ctx, dut)

	defer func() {
		if err := restoreAfterPowerwash(ctx, statefulImage, dut, pushedFiles); err != nil {
			retErr = errors.Join(retErr, errors.Wrap(err, "failed to restore after powerwash"))
		}
	}()

	// Initiate powerwash.
	testing.ContextLog(ctx, "Performing powerwash")
	if powerwashFn != nil {
		if err := powerwashFn(ctx); err != nil {
			return errors.Wrap(err, "custom powerwash function failed")
		}
	} else {
		// Default powerwash mechanism.
		if err := linuxssh.WriteFile(ctx, dut.Conn(), "/mnt/stateful_partition/factory_install_reset", []byte("safe fast keepimg"), 0644); err != nil {
			return errors.Wrap(err, "failed to write to powerwash marker file")
		}
		if err := dut.Reboot(ctx); err != nil {
			return errors.Wrap(err, "failed to reboot to perform powerwash")
		}
	}

	return nil
}
