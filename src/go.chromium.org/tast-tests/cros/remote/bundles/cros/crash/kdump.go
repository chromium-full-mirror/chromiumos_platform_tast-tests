func init() {
	testing.AddTest(&testing.Test{
		Func: Kdump,
		Desc: "Verifies kdump functionality",
		Contacts: []string{
			"jiejiang@google.com",
			"chromeos-platform-stability-team@google.com",
		},
		BugComponent: "b:1672909",
		Attr:         []string{"group:mainline", "informational"},
		SoftwareDeps: []string{"kdump", "reboot", "pstore"},
		ServiceDeps:  []string{"tast.cros.crash.FixtureService"},
		Timeout:      10 * time.Minute,
	})
}

// Kdump test performs the following steps:
// 1. Enable kdump on DUT and reboot.
// 2. Verify that the kdump image is loaded.
// 3. Trigger a kernel crash.
// 4. Wait for DUT to be reconnected.
// 5. Check the reports generated by the crash reporter.
// 6. Check the artifacts generated by kdump.
func Kdump(ctx context.Context, s *testing.State) {
	// Shorten deadline to leave time for cleanup.
	cleanupCtx := ctx
	ctx, cancel := ctxutil.Shorten(ctx, 10*time.Second)
	defer cancel()

	d := s.DUT()

	// Enable kdump. This may reboot the device so do it before setting up the
	// crash service.
	disableKdumpFunc, err := kdump.EnableKdump(ctx, d)
	if err != nil {
		s.Fatal("Failed to enable kdump: ", err)
	}
	defer func() {
		if err := disableKdumpFunc(cleanupCtx); err != nil {
			s.Error("Failed to disable kdump in cleanup: ", err)
		}
	}()

	// This test will trigger a reboot which will invalidate the RPC client and
	// the fixture service client. Create some vars and helper functions in
	// advance to make the logic cleaner.
	var cl *rpc.Client
	var fs crashservice.FixtureServiceClient
	createFixtureServiceClient := func() {
		var err error
		cl, err = rpc.Dial(ctx, d, s.RPCHint())
		if err != nil {
			s.Fatal("Failed to create crash client: ", err)
		}
		fs = crashservice.NewFixtureServiceClient(cl.Conn)
	}

	createFixtureServiceClient()
	defer func() {
		if cl != nil {
			if err := cl.Conn.Close(); err != nil {
				s.Error("Failed to close client connection: ", err)
			}
		}
	}()

	// Note that fs.SetUp() will back up the crash folder (/var/spool/crash) so
	// that the test will start from a clean state.
	if _, err := fs.SetUp(ctx, &crashservice.SetUpCrashTestRequest{}); err != nil {
		s.Fatal("Failed to set up crash test fixture: ", err)
	}
	defer func() {
		if fs != nil {
			if _, err := fs.TearDown(cleanupCtx, &empty.Empty{}); err != nil {
				s.Error("Failed to tear down crash fixture service: ", err)
			}
		}
	}()

	s.Log("Checking if kdump image is loaded")
	if out, err := d.Conn().CommandContext(ctx, "cat", kdump.KexecCrashLoadedPath).Output(exec.DumpLogOnError); err != nil {
		s.Fatalf("Failed to read %s: %v", kdump.KexecCrashLoadedPath, err)
	} else if strings.TrimSpace(string(out)) != "1" {
		s.Fatalf("Unexpected value in %s: got %s, want 1", kdump.KexecCrashLoadedPath, string(out))
	}

	// Since there can be kdump files from other crashes before the test start,
	// let's check the files before the test.
	beforeFiles, err := kdump.ListKdumpFiles(ctx, d)
	if err != nil {
		s.Fatal("Failed to list kdump files before crash: ", err)
	}

	// Force all cached file system data to be written to disk. Otherwise kernel
	// panic might discard this data, resulting in unexpected file corruption
	// and cascading test failures after reboot.
	if err := d.Conn().CommandContext(ctx, "sync").Run(testexec.DumpLogOnError); err != nil {
		s.Fatal("Failed to invoke sync: ", err)
	}

	// Trigger a panic. By the time RebootWithCommand() returns the DUT will be
	// reconnected.
	s.Log("Triggering kernel crash")
	if err := d.RebootWithCommand(ctx, "sh", "-c", "echo c > /proc/sysrq-trigger"); err != nil {
		s.Fatal("Failed to trigger kernel crash: ", err)
	}

	// Recreate the clients.
	cl = nil
	fs = nil
	createFixtureServiceClient()

	s.Log("Verifying crash reporter artifacts")
	req := &crashservice.WaitForCrashFilesRequest{
		Dirs: []string{"/var/spool/crash"},
		Regexes: []string{
			`kernel.*\.kcrash`,
		},
	}
	if resp, err := fs.WaitForCrashFiles(ctx, req); err != nil {
		s.Fatal("Failed to wait for crash files: ", err)
	} else {
		// We expect only 1 kernel crash.
		matches := resp.Matches
		if len(matches) != 1 {
			s.Errorf("Unexpected number of matched groups: got %d, want 1", len(matches))
		}
		files := matches[0].Files
		if len(files) != 1 {
			s.Errorf("Unexpected number of matched files: got %d, want 1", len(files))

		}

		// Remove the crash report by matching the prefix.
		prefix := strings.TrimSuffix(files[0], "kcrash")
		s.Logf("Removing %s* for cleanup", prefix)
		if _, err := s.DUT().Conn().CommandContext(ctx, "sh", "-c", "rm "+prefix+"*").Output(testexec.DumpLogOnError); err != nil {
			s.Error("Failed to remove the crash report for cleanup: ", err)
		}
	}

	s.Log("Verifying kdump artifacts")
	afterFiles, err := kdump.ListKdumpFiles(ctx, d)
	if err != nil {
		s.Fatal("Failed to list kdump files after crash: ", err)
	}
	newFiles := stringSliceDifference(afterFiles, beforeFiles)
	count := 0
	for _, f := range newFiles {
		if strings.HasSuffix(f, ".core") {
			count++
		}
	}
	if count != 1 {
		s.Errorf("Unexpected number of new core files: got %d, want 1", count)
	}

	// TODO(b/453571009): Verify that console-ramoops was not overwritten by the
	// kdump kernel.

	// Remove the kdump artifact.
	for _, f := range newFiles {
		fullPath := filepath.Join(kdump.KdumpDir, f)
		s.Logf("Removing %s for cleanup", fullPath)
		if _, err := s.DUT().Conn().CommandContext(ctx, "rm", fullPath).Output(testexec.DumpLogOnError); err != nil {
			s.Error("Failed to remove the kdump artifact for cleanup: ", err)
		}
	}
}

// stringSliceDifference returns elements in 'superset' that are not in
// 'subset'. It assumes 'superset' contains all elements of 'subset'.
func stringSliceDifference(superset, subset []string) []string {
	m := make(map[string]bool)
	for _, e := range subset {
		m[e] = true
	}
	var diff []string
	for _, e := range superset {
		if !m[e] {
			diff = append(diff, e)
		}
	}
	return diff
}
