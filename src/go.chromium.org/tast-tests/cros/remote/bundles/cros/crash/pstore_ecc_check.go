func init() {
	testing.AddTest(&testing.Test{
		Func:         PstoreECCCheck,
		Desc:         "Triggers a kernel crash to verify that the ECC status is correctly reported in the resulting pstore/ramoops log",
		Contacts:     []string{"chromeos-platform-stability-team@google.com", "naoyatezuka@google.com"},
		BugComponent: "b:1672909",
		Attr:         []string{"group:mainline", "informational"},
		SoftwareDeps: []string{"ecc", "reboot", "pstore"},
		ServiceDeps:  []string{"tast.cros.crash.FixtureService"},
		Timeout:      5 * time.Minute,
	})
}

const (
	systemCrashDir     = "/var/spool/crash"
	consoleRamoopsFile = "/sys/fs/pstore/console-ramoops-0"
)

var (
	noErrorsRegex        = regexp.MustCompile(`No errors detected`)
	correctedErrorsRegex = regexp.MustCompile(`\d+ Corrected bytes, \d+ unrecoverable blocks`)
)

func cleanCrashDir(ctx context.Context, d *dut.DUT) error {
	cmd := fmt.Sprintf("rm -f %s/*", systemCrashDir)
	return d.Conn().CommandContext(ctx, "sh", "-c", cmd).Run(testexec.DumpLogOnError)
}

// checkECCInLog checks if the file at filepath on d contains the message for
// ECC.
func checkECCInLog(ctx context.Context, d *dut.DUT, filePath string) error {
	testing.ContextLog(ctx, "Checking for ECC status in ", filePath)
	lastLine, err := d.Conn().CommandContext(ctx, "tail", "-n", "1", filePath).Output()
	if err != nil {
		return errors.Wrapf(err, "failed to read last line of %s", filePath)
	}
	testing.ContextLogf(ctx, "The last line of %s: %q", filePath, lastLine)

	// Here we focus on whether the ECC feature is enabled,
	// and don't care if ECC can correct corruption in the ramoops region completely.
	if noErrorsRegex.Match(lastLine) {
		testing.ContextLog(ctx, "ECC is enabled and no errors were detected")
	} else if correctedErrorsRegex.Match(lastLine) {
		testing.ContextLog(ctx, "ECC is enabled and errors were detected")
	} else {
		return errors.Errorf("ECC status not found in the last line of %s", filePath)
	}
	return nil
}

// PstoreECCCheck triggers a kernel crash to verify that the ECC status is
// correctly reported in the resulting pstore/ramoops log.
func PstoreECCCheck(ctx context.Context, s *testing.State) {
	// Shorten deadline to leave time for cleanup.
	cleanupCtx := ctx
	ctx, cancel := ctxutil.Shorten(ctx, 5*time.Second)
	defer cancel()

	d := s.DUT()

	cl, err := rpc.Dial(ctx, d, s.RPCHint())
	if err != nil {
		s.Fatal("Failed to connect to the RPC service on the DUT: ", err)
	}
	defer func() {
		if cl != nil {
			cl.Close(cleanupCtx)
		}
	}()

	fs := crashservice.NewFixtureServiceClient(cl.Conn)
	if _, err := fs.SetUp(ctx, &crashservice.SetUpCrashTestRequest{}); err != nil {
		s.Fatal("Failed to set up crash test: ", err)
	}

	// This is a bit delicate. If the test fails _before_ we panic the machine,
	// we need to do TearDown then, and on the same connection (so we can close Chrome).
	//
	// If it fails to reconnect, we do not need to clean these up.
	//
	// Otherwise, we need to run TearDown on the re-established connection to the machine.
	defer func() {
		s.Log("Cleaning up")
		if fs != nil {
			if _, err := fs.TearDown(cleanupCtx, &empty.Empty{}); err != nil {
				s.Error("Failed to tear down: ", err)
			}
		}
	}()

	// Force all cached file system data to be written to disk.
	// Otherwise kernel panic might discard this data, resulting in unexpected file corruption
	// and cascading test failures after reboot.
	if err := d.Conn().CommandContext(ctx, "sync").Run(testexec.DumpLogOnError); err != nil {
		s.Fatal("Failed to invoke sync: ", err)
	}

	s.Log("Triggering kernel crash and waiting for the DUT to reboot")
	if err := d.RebootWithCommand(ctx, "sh", "-c", "echo PANIC > /sys/kernel/debug/provoke-crash/DIRECT"); err != nil {
		s.Fatal("Failed to trigger kernel crash: ", err)
	}

	// When we lost the connection, these connections broke.
	cl.Close(ctx)
	cl = nil
	fs = nil

	cl, err = rpc.Dial(ctx, d, s.RPCHint())
	if err != nil {
		s.Fatal("Failed to connect to the RPC service on the DUT: ", err)
	}
	fs = crashservice.NewFixtureServiceClient(cl.Conn)

	const base = `kernel\.\d{8}\.\d{6}\.\d+\.0`
	// We don't have to wait for console-ramoops file to appear because it
	// will be generated by the kernel, not by the crash reporter.
	waitReq := &crashservice.WaitForCrashFilesRequest{
		Dirs:    []string{systemCrashDir},
		Regexes: []string{base + `\.kcrash`, base + `\.meta`},
	}
	s.Log("Waiting for files to become present")
	res, err := fs.WaitForCrashFiles(ctx, waitReq)
	// If WaitForCrashFiles fails, res can be nil. In that case, we can't
	// use res.Matches to remove the specific crash files. As a fallback,
	// clean the entire crash directory to ensure no crash files are left
	// behind.
	if err != nil {
		if cleanErr := cleanCrashDir(cleanupCtx, d); cleanErr != nil {
			s.Log("Failed to clean crash directory as a fallback: ", cleanErr)
		}
		s.Fatal("Failed to find crash files: ", err)
	}
	defer func() {
		removeReq := &crashservice.RemoveAllFilesRequest{
			Matches: res.Matches,
		}
		if _, err := fs.RemoveAllFiles(cleanupCtx, removeReq); err != nil {
			s.Error("Failed to remove crash files: ", err)
		}
	}()

	if len(res.Matches) != 2 {
		s.Errorf("Wrong number of crash file match groups: got %d, want 2", len(res.Matches))
	}
	for _, match := range res.Matches {
		if !strings.HasSuffix(match.Regex, ".kcrash") {
			continue
		}
		// We expect exactly there is exactly one .kcrash file from our single panic command.
		if len(match.Files) != 1 {
			s.Errorf("Wrong number of kcrash files: got %d, want 1", len(match.Files))
		}
		kcrashFile := match.Files[0]
		if err := checkECCInLog(ctx, d, kcrashFile); err != nil {
			s.Error("Check failed for kcrash file: ", err)
		}
	}

	// We assume we have only one console-ramoops file since it won't
	// persist across reboot we trigger in this test.
	if err := checkECCInLog(ctx, d, consoleRamoopsFile); err != nil {
		s.Error("Check failed for console-ramoops file: ", err)
	}
}
