package inputs

import (
	"math"

	"go.chromium.org/tast/core/errors"
	"gonum.org/v1/gonum/mat"
)

const (
	minReferencePathSize = 10
)

// FullImageResult contains the output of the HMR full image sliding analysis.
type FullImageResult struct {
	Passed      bool
	TotalMSE    float64 // total mean squared error of all paths.
	Epsilon     float64 // maximum distance between start points on reference and result paths in mm.
	PathResults []*PathResult
}

// PathResult contains the output of the HMR full image sliding analysis over a single path.
type PathResult struct {
	PathMSE              float64 // average mean squared error for all calculations on path.
	SuccessfulFitRate    float64 // percentage of curve fittings performed with an r2 value greater than the threshold.
	NumberOfCalculations float64 // number of curve fitting calculations performed.
	ReferencePathLength  int
	ResultPathLength     int
	BubbleRadius         float64 // value in (mm) used in the sliding window analysis for this path.
}

func euclideanDistance(pointA, pointB *hmrNode) float64 {
	return math.Sqrt(math.Pow(pointA.coorX-pointB.coorX, 2) + math.Pow(pointA.coorY-pointB.coorY, 2))
}

// leastSquaredFit performs a polynomial fitting on a set of points using least squared, and returns the coefficients.
func leastSquaredFit(x, y []float64, degree int) ([]float64, error) {
	if len(x) != len(y) {
		return nil, errors.Errorf("length of x and y arrays must be the same. len(x): %v len(y): %v", len(x), len(y))
	}
	numberOfCoefficients := degree + 1

	xVals := make([]float64, numberOfCoefficients*len(x))
	for i := range x {
		for j := 0; j < numberOfCoefficients; j++ {
			xVals[i*numberOfCoefficients+j] = math.Pow(x[i], float64(j))
		}
	}

	xMatrix := mat.NewDense(len(x), numberOfCoefficients, xVals)
	yMatrix := mat.NewDense(len(y), 1, y)

	resultMatrix := mat.NewDense(numberOfCoefficients, 1, nil)
	err := resultMatrix.Solve(xMatrix, yMatrix)
	if err != nil {
		return nil, err
	}

	coefs := mat.Col(nil, 0, resultMatrix)
	return coefs, nil
}

// extractReferencePaths extracts a set of paths from reference point data.
// A path is a contiguous sets of points where pressure > 0.
// The reference dataset is generated by manually running a script on a DUT,
// which collects its touch events. It is always expected that the reference
// dataset ends with a point with pressure == 0.
func extractReferencePaths(points []*hmrNode) [][]*hmrNode {
	var paths [][]*hmrNode
	var path []*hmrNode

	for _, point := range points {
		if point.pressure > 0 {
			if len(path) > 0 {
				// If pressure > 0 and an existing path is open, add this point to it.
				previousPoint := path[len(path)-1]
				if previousPoint.coorX != point.coorX || previousPoint.coorY != point.coorY {
					path = append(path, point)
				}
			} else {
				// If pressure > 0 and there is not an existing path open. Create a new one.
				path = append(path, point)
			}
		} else {
			if len(path) > 0 {
				if len(path) > minReferencePathSize {
					// If pressure == 0, and an existing path is open. Close the path, and add it to list of paths.
					paths = append(paths, path)
				}
				path = []*hmrNode{}
			} else {
				// If pressure == 0, and there isn't a path open. Do nothing.
				continue
			}
		}
	}

	return paths
}

// extractResultsPaths extracts paths from the results dataset, using the
// smallest epsilon value possible.
func extractResultsPaths(resultPoints []*hmrNode, referencePaths [][]*hmrNode, resultScreenDiagonalDistance float64) ([][]*hmrNode, float64, error) {
	var finalResultPaths [][]*hmrNode
	epsilon := -1.0
	left := 0.0
	right := resultScreenDiagonalDistance
	// Perform a binary search until the smallest epsilon value that creates the same number of results paths as reference paths is found.
	for left <= right {
		mid := math.Floor((left + right) / 2)
		resultPaths := matchReferencePathToResultPath(resultPoints, referencePaths, mid)
		if len(resultPaths) < len(referencePaths) {
			left = mid + 1
		} else {
			right = mid - 1
			if len(resultPaths) == len(referencePaths) {
				epsilon = mid
				finalResultPaths = resultPaths
			}
		}
	}

	if epsilon < 0 {
		return nil, -1, errors.New("could not find a valid epsilon")
	}
	return finalResultPaths, epsilon, nil
}

// matchReferencePathToResultPath attempts to extract a result path from the
// results dataset. This involves matching the start and end points of each of
// the reference paths, to points within the results dataset within epsilon
// value.
func matchReferencePathToResultPath(resultPoints []*hmrNode, referencePaths [][]*hmrNode, epsilon float64) [][]*hmrNode {
	var resultPaths [][]*hmrNode
	var path []*hmrNode
	// Keep track of the next reference path that we're trying to match.
	referencePathIdx := 0
	// Iterate through all results points.
	// When we find a result point with pressure > 0, that was preceded by a result point with pressure == 0, and the result point is within epsilon distance of the start of the next reference path, we create a new result path.
	// We continue iterating through result points until we find a point with == 0, preceded by a point with pressure > 0, and within epsilon distance of the end of the next reference path, we then close the result path, and increment the reference path counter.
	for i := range resultPoints {
		if resultPoints[i].pressure > 0 {
			if len(path) > 0 {
				// If pressure > 0 and a path exists, add this point to the path.
				path = append(path, resultPoints[i])
			} else {
				// If pressure > 0, and the previous point's pressure == 0, and the point is within epsilon of the next reference points start point. Create a new path.
				referencePathStartPoint := referencePaths[referencePathIdx][0]
				if (i == 0 || resultPoints[i-1].pressure == 0) && euclideanDistance(resultPoints[i], referencePathStartPoint) <= epsilon {
					path = append(path, resultPoints[i])
				}
			}
		} else {
			if len(path) > 0 {
				// If pressure == 0, and the previous point's pressure > 0, and the previous point was within epsilon of the next reference points end point. Close the path.
				referencePathEndPoint := referencePaths[referencePathIdx][len(referencePaths[referencePathIdx])-1]
				if resultPoints[i-1].pressure > 0 && euclideanDistance(resultPoints[i-1], referencePathEndPoint) <= epsilon {
					resultPaths = append(resultPaths, path)
					referencePathIdx++
					if referencePathIdx >= len(referencePaths) {
						break
					}
					path = []*hmrNode{}
				} else {
					// If pressure == 0 and an open path exists. Add this point to it.
					path = append(path, resultPoints[i])
				}
			}
		}
	}
	if len(path) > 0 {
		resultPaths = append(resultPaths, path)
	}
	return resultPaths
}
