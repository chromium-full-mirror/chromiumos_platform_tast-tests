// Package certificate contains test certificates for use in public key cryptography. These can be used in both remote
// and local tests.
package certificate

// CertStore holds a set of credentials which share the same CA certificate.
type CertStore struct {
	CACred     Credential
	ServerCred Credential
	ClientCred Credential

	ExpiredServerCred Credential
}

// Credential holds a pair of certificate and private key.
type Credential struct {
	Cert       string
	PrivateKey string
	Info       Info
}

// Info holds the information contained in the certificate.
type Info struct {
	CommonName   string
	Organization string
}

