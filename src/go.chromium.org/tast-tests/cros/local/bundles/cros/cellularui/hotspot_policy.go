func HotspotPolicy(ctx context.Context, s *testing.State) {
	cleanupCtx := ctx
	ctx, cancel := ctxutil.Shorten(ctx, 10*time.Second)
	defer cancel()

	fdms := s.FixtValue().(fakedms.HasFakeDMS).FakeDMS()

	// Start a Chrome instance that will fetch policies from the FakeDMS.
	cr, err := chrome.New(ctx,
		chrome.FakeLogin(chrome.Creds{User: fixtures.Username, Pass: fixtures.Password}),
		chrome.EnableFeatures("TetheringExperimentalFunctionality"),
		chrome.DMSPolicy(fdms.URL),
		chrome.KeepEnrollment())
	if err != nil {
		s.Fatal("Chrome login failed: ", err)
	}
	defer func(ctx context.Context) {
		policyutil.ResetChrome(ctx, fdms, cr)
		cr.Close(ctx)
	}(cleanupCtx)

	helper := s.FixtValue().(*cellular.FixtData).Helper
	if _, err := helper.Connect(ctx); err != nil {
		s.Fatal("Failed to connect to cellular service: ", err)
	}

	tconn, err := cr.TestAPIConn(ctx)
	if err != nil {
		s.Fatal("Failed to create Test API connection: ", err)
	}

	hs, err := ossettings.LaunchAtPage(ctx, tconn, ossettings.Internet)
	if err != nil {
		s.Fatal("Failed to launch network page: ", err)
	}
	defer faillog.DumpUITreeWithScreenshotOnError(cleanupCtx, s.OutDir(), s.HasError, cr, "ui_tree")

	if err := hs.ToggleHotspot(ctx, tconn, cr, true); err != nil {
		s.Fatal("Failed to toggle on hotspot: ", err)
	}

	globalConfig := &policy.ONCGlobalNetworkConfiguration{
		AllowCellularHotspot: false,
	}

	deviceNetworkPolicy := &policy.DeviceOpenNetworkConfiguration{
		Val: &policy.ONC{
			GlobalNetworkConfiguration: globalConfig,
			NetworkConfigurations:      []*policy.ONCNetworkConfiguration{},
		},
	}

	// Apply Global Network Configuration.
	if err := policyutil.ServeAndRefresh(ctx, fdms, cr, []policy.Policy{deviceNetworkPolicy}); err != nil {
		s.Fatal("Failed to ServeAndRefresh ONC policy: ", err)
	}

	const title = "Hotspot is off"
	const message = "Your administrator has turned hotspot off."
	if _, err := ash.WaitForNotification(ctx, tconn, 5*time.Second, ash.WaitTitle(title), ash.WaitMessageContains(message)); err != nil {
		s.Fatal("Failed to wait for the notification with title: Hotspot is off, err: ", err)
	}

	ui := uiauto.New(tconn)
	if err := uiauto.Combine("Verify hotspot is off and toggle disabled",
		// TODO(b/370733459): Check the hotspot label to determine if the hotspot is enabled after the a11y tree is updated.
		ui.WaitUntilCheckedState(ossettings.HotspotToggle, false),
		ui.CheckRestriction(ossettings.HotspotToggle, restriction.Disabled),
	)(ctx); err != nil {
		s.Fatal("Failed to verify hotspot is off and toggle disabled: ", err)
	}

	if err := quicksettings.NavigateToHotspotDetailedView(ctx, tconn); err != nil {
		s.Fatal("Failed to navigate to hotspot detailed view: ", err)
	}

	if err := uiauto.Combine("Verify policy icon is shown and no response when clicking on toggle",
		ui.WaitUntilExists(quicksettings.HotspotPolicyImage),
		ui.LeftClick(quicksettings.HotspotDetailedViewToggle),
		ui.EnsureGoneFor(quicksettings.HotspotTurningOnText, 3*time.Second),
	)(ctx); err != nil {
		s.Fatal("Failed to see policy icon or toggle is not disabled: ", err)
	}
}
