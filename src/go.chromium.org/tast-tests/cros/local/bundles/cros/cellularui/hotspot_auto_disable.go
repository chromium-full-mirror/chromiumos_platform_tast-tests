func HotspotAutoDisable(ctx context.Context, s *testing.State) {
	cleanupCtx := ctx
	ctx, cancel := ctxutil.Shorten(ctx, 10*time.Second)
	defer cancel()

	cr, err := chrome.New(ctx, chrome.EnableFeatures("TetheringExperimentalFunctionality"))
	if err != nil {
		s.Fatal("Failed to create a new instance of Chrome: ", err)
	}
	defer cr.Close(cleanupCtx)

	helper := s.FixtValue().(*cellular.FixtData).Helper
	if _, err := helper.Connect(ctx); err != nil {
		s.Fatal("Failed to connect to cellular service: ", err)
	}

	tconn, err := cr.TestAPIConn(ctx)
	if err != nil {
		s.Fatal("Failed to create Test API connection: ", err)
	}

	hs, err := ossettings.LaunchAtHotspotSubpage(ctx, tconn, cr)
	if err != nil {
		s.Fatal("Failed to open hotspot subpage: ", err)
	}
	defer hs.Close(cleanupCtx)
	defer faillog.DumpUITreeWithScreenshotOnError(cleanupCtx, s.OutDir(), s.HasError, cr, "ui_tree")

	// Verify auto disable toggle is on
	if err := hs.SetToggleOption(cr, "Turn off hotspot automatically", true)(ctx); err != nil {
		s.Fatal("Failed to toggle on auto disable toggle: ", err)
	}

	if err := hs.ToggleHotspot(ctx, tconn, cr, true); err != nil {
		s.Fatal("Failed to toggle on hotspot: ", err)
	}

	// GoBigSleepLint: Verify hotspot is turned off automatically in 5 minutes.
	testing.Sleep(ctx, 5*time.Minute)
	const title = "Hotspot is off"
	const message = "Due to inactivity, hotspot has been turned off."
	if _, err := ash.WaitForNotification(ctx, tconn, 10*time.Second, ash.WaitTitle(title), ash.WaitMessageContains(message)); err != nil {
		s.Fatal("Failed to wait for the notification with title: Hotspot is off, err: ", err)
	}

	if err := hs.WaitUntilCheckedState(ossettings.HotspotToggle, false)(ctx); err != nil {
		s.Fatal("Failed to verify hotspot is turned off: ", err)
	}
}
