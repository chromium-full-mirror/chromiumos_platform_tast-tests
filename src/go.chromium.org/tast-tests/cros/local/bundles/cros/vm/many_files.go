func runOneTestCase(ctx context.Context, toGuest *os.File, reader *bufio.Reader, testCase, outDir string, traceCmdEvents []string) error {
	var ti *tracing.TraceInstance
	if len(traceCmdEvents) > 0 {
		outPath := filepath.Join(outDir, fmt.Sprintf("%s-trace.dat", strings.TrimSuffix(testCase, "()")))
		var err error

		ti, err := tracing.CreateTraceInstance(ctx, "tast",
			tracing.CPUBufferKiB(15000),
			tracing.EnableEvents(traceCmdEvents...),
			tracing.RecordOnDiskMode(outPath))
		if err != nil {
			return errors.Wrap(err, "failed to start trace-cmd")
		}
		defer ti.Finalize(ctx)
	}

	testing.ContextLog(ctx, "Start test case: ", testCase)
	if _, err := toGuest.WriteString(guestconn.Run); err != nil {
		return errors.Wrap(err, "failed to write a message to toGuestFIFO")
	}
	if _, err := guestconn.WaitForPrefix(reader, []string{guestconn.End}); err != nil {
		return errors.Wrap(err, "failed to wait for END")
	}
	testing.ContextLog(ctx, "Finished test case: ", testCase)

	// Stop trace-cmd
	if ti != nil {
		if err := ti.Save(ctx, ""); err != nil {
			return errors.Wrap(err, "failed to stop trace-cmd")
		}
	}

	return nil
}

// ManyFiles is used as one of the standard SW gates (go/pe-sw-gates).
// Please ask to crosvm-core@ if you want to modify or delete this test.
func ManyFiles(ctx context.Context, s *testing.State) {
	// Reserve 5 seconds for clean up
	cleanupCtx := ctx
	ctx, cancel := ctxutil.Shorten(ctx, 5*time.Second)
	defer cancel()

	// Create a temporary directory that shared with the guest so the guest can put test logs.
	td, err := ioutil.TempDir("/usr/local/tmp", "tast.vm.ManyFiles.")
	if err != nil {
		s.Fatal("Failed to create temporary directory: ", err)
	}
	defer os.RemoveAll(td)

	p := s.Param().(manyFilesParams)

	kernelPath := ""
	username := ""

	if p.kernel == "termina" {
		data := s.FixtValue().(dlc.FixtData)
		username = data.Chrome.NormalizedUser()
		kernelPath = data.Kernel
	} else if p.kernel == "arcvm" {
		username = s.FixtValue().(chrome.HasChrome).Chrome().NormalizedUser()
		kernelPath = "/opt/google/vms/android/vmlinux"
	} else {
		s.Fatal("Failed to identify guest kernel: ", p.kernel)
	}

	if kernelPathOverride, ok := s.Var("vm.ManyFiles.kernelPath"); ok {
		kernelPath = kernelPathOverride
	}

	// Create a temporary directory on the encrypted file system on `/home/root/${user hash}/`.
	// The test script in the guest write data into this directory.

	// First, check if enough space is available.
	const MiB uint64 = 1024 * 1024
	blockSize := 128 * MiB // 128 MiB is large enough to have test files and filesystem metadata.
	if err := storage.CheckFreeSpace(ctx, "/home/root", blockSize); err != nil {
		s.Fatal("Failed to check free space: ", err)
	}
	// Then, create a directory
	rootCryptDir, err := cryptohome.SystemPath(ctx, username)
	if err != nil {
		s.Fatal("Failed to get the cryptohome directory: ", err)
	}
	ud, err := ioutil.TempDir(rootCryptDir, "tast.vm.ManyFiles.")
	defer os.RemoveAll(ud)

	opt, err := storage.NewOption(p.kind, p.cache, p.caseFold, p.negativeTimeout)
	if err != nil {
		s.Fatal("Failed to create storage option: ", err)
	}

	outputJSON := filepath.Join(s.OutDir(), "test-result.json")
	scriptArgs := []string{
		"--kind",
		opt.Kind,
		"--mount-src",
		opt.Tag,
		"--working-dir",
		td,
		"--output-json",
		outputJSON,
	}

	var blockPath string
	var cleanUp func(context.Context)
	if opt.Kind == "block_lvm" {
		blockPath, cleanUp, err = storage.SetUpLogicVolume(ctx, "vm_test_lv", blockSize)
		if err != nil {
			s.Fatal("Failed to set up logic volume: ", err)
		}
	} else {
		blockPath, cleanUp, err = storage.SetUpBlockFile(ctx, ud, blockSize)
		if err != nil {
			s.Fatal("Failed to set up block image file: ", err)
		}
	}
	defer cleanUp(cleanupCtx)

	// Constructs a crosvm command
	ps, err := storage.GenCrosvmCmd(td, ud, s.OutDir(), kernelPath,
		blockPath,
		s.DataPath(runManyFiles),
		opt, scriptArgs)
	if err != nil {
		s.Fatal("Failed to construct crosvm command: ", err)
	}

	// Use FIFO files as the guest's serial device.
	toGuestFIFO, fromGuestFIFO, err := guestconn.CreateGuestConn(td, ps)
	if err != nil {
		s.Fatal("Failed to create guest connection: ", err)
	}

	// Increase the max open file limit as the benchmark creates a lot of files.
	args := append([]string{"--nofile=262144", "crosvm"}, ps.ToArgs()...)

	cmd := testexec.CommandContext(ctx, "prlimit", args...)

	// Construct s a crosvm command
	output, err := os.Create(filepath.Join(s.OutDir(), "crosvm.log"))
	if err != nil {
		s.Fatal("Failed to create crosvm log file: ", err)
	}
	defer output.Close()

	cmd.Stdout = output
	cmd.Stderr = output

	s.Log("Start crosvm command: ", cmd)

	if err := cmd.Start(); err != nil {
		s.Fatal("Failed to run crosvm: ", err)
	}

	toGuest, fromGuest, cleanUp, err := guestconn.OpenGuestConn(ctx, toGuestFIFO, fromGuestFIFO)
	defer cleanUp(cleanupCtx)
	if err != nil {
		s.Fatal("Failed to open guest connection: ", err)
	}
	reader := bufio.NewReaderSize(fromGuest, 4096)

	var traceCmdEvents []string
	if traceCmdEventsVar.Value() != "" {
		traceCmdEvents = strings.Split(traceCmdEventsVar.Value(), ",")
	}

	for {
		// Waiting for the guest sending messages with special prefixes.
		line, err := guestconn.WaitForPrefix(reader, []string{guestconn.PrefixReady, guestconn.PrefixReadyNoDrop, guestconn.Complete})
		if err != nil {
			s.Fatal("Failed to wait for 'READY' or 'COMPLETE': ", err)
		}
		// "COMPLETE" means that the all test cases completed
		if strings.HasPrefix(line, guestconn.Complete) {
			s.Log("All the guest test cases are completed")
			break
		}

		trimed := strings.TrimRight(line, " \r\n")
		var testCase string
		dropCaches := true
		if strings.HasPrefix(trimed, guestconn.PrefixReadyNoDrop) {
			dropCaches = false
			testCase = strings.TrimPrefix(trimed, guestconn.PrefixReadyNoDrop)
		} else {
			testCase = strings.TrimPrefix(trimed, guestconn.PrefixReady)
		}
		s.Logf("Guest is ready for test case %q", testCase)

		// Drop host caches before running a test in the guest
		if dropCaches {
			if err := disk.DropCaches(ctx); err != nil {
				s.Fatal("Failed to drop caches: ", err)
			}
		}

		if err := runOneTestCase(ctx, toGuest, reader, testCase, s.OutDir(), traceCmdEvents); err != nil {
			s.Errorf("Failed test on %s : %v", testCase, err)
		}
	}

	if err := cmd.Wait(testexec.DumpLogOnError); err != nil {
		s.Fatal("Failed to wait crosvm: ", err)
	}

	jsonData, err := ioutil.ReadFile(outputJSON)
	if err != nil {
		s.Fatal("Failed to read fio results: ", err)
	}

	var result map[string]float64
	json.Unmarshal(jsonData, &result)
	perfValues := perf.NewValues()

	for name, ms := range result {
		perfValues.Set(perf.Metric{
			Name:      name,
			Unit:      "milliseconds",
			Direction: perf.SmallerIsBetter,
		}, ms)
	}
	perfValues.Save(s.OutDir())
}
