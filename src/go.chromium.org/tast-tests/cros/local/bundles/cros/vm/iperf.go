const runIperfTest string = "run-iperf-test.sh"

type virtqueueType int
type netProtocol int
type guestKernel int

const (
	split virtqueueType = iota
	packed
)

const (
	tcp netProtocol = iota
	udp
	udpReverse
)

const (
	arcvm guestKernel = iota
	termina
)

func (vt virtqueueType) String() string {
	switch vt {
	case split:
		return "split"
	case packed:
		return "packed"
	}
	return "unknown"
}

func (np netProtocol) String() string {
	switch np {
	case tcp:
		return "tcp"
	case udp:
		return "udp"
	case udpReverse:
		return "udpReverse"
	}
	return "unknown"
}

func (gk guestKernel) String() string {
	switch gk {
	case arcvm:
		return "arcvm"
	case termina:
		return "termina"
	}
	return "unknown"
}

