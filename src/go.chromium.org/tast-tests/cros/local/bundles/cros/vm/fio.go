func Fio(ctx context.Context, s *testing.State) {
	// Reserve 5 seconds for clean up
	cleanupCtx := ctx
	ctx, cancel := ctxutil.Shorten(ctx, 5*time.Second)
	defer cancel()

	// Create a temporary directory that shared with the guest so the guest can put test logs.
	td, err := ioutil.TempDir("/usr/local/tmp", "tast.vm.Fio.")
	if err != nil {
		s.Fatal("Failed to create temporary directory: ", err)
	}
	defer os.RemoveAll(td)

	data := s.FixtValue().(dlc.FixtData)
	kernelPath := data.Kernel
	if kernelPathOverride, ok := s.Var("vm.Fio.kernelPath"); ok {
		kernelPath = kernelPathOverride
	}

	// Create a temporary directory on the encrypted file system on `/home/root/${user hash}/`.
	// This directory will be accessed by FIO.
	username := data.Chrome.NormalizedUser()
	rootCryptDir, err := cryptohome.SystemPath(ctx, username)
	if err != nil {
		s.Fatal("Failed to get the cryptohome directory: ", err)
	}
	ud, err := ioutil.TempDir(rootCryptDir, "tast.vm.Fio.")
	defer os.RemoveAll(ud)

	p := s.Param().(param)
	kind := p.kind
	job := p.job
	fioOutput := filepath.Join(s.OutDir(), "fio-output.json")

	opt, err := storage.NewOption(kind, "auto", false)
	if err != nil {
		s.Fatal("Failed to create storage option: ", err)
	}

	// Disables CPU frequency scaling and thermal throttling
	// to have more stable results
	cleanup, err := cpu.SetUpBenchmark(ctx)
	if err != nil {
		s.Fatal("Failed to perform setUpBenchmark: ", err)
	}
	defer cleanup(cleanupCtx)

	scriptArgs := []string{
		opt.Kind,
		opt.Tag,
		td,
		fioOutput,
		s.DataPath(job),
	}

	var blockPath string
	// Create a disk image for virtio block
	if opt.Kind == "block_lvm" {
		blockPath, cleanup, err = storage.SetUpLogicVolume(ctx, "vm_test_lv")
		if err != nil {
			s.Fatal("Failed to set up logic volume: ", err)
		}
		defer cleanup(cleanupCtx)
	} else {
		blockPath, cleanup, err = storage.SetUpBlockFile(ctx, ud)
		if err != nil {
			s.Fatal("Failed to set up block image file: ", err)
		}
		defer cleanup(cleanupCtx)
	}

	ps, err := storage.GenCrosvmCmd(td, ud, s.OutDir(), kernelPath, blockPath, s.DataPath(runFio), opt, scriptArgs)
	if err != nil {
		s.Fatal("Failed to construct crosvm command: ", err)
	}

	// Increase the max open file limit as the benchmark creates a lot of files.
	args := append([]string{"--nofile=262144", "crosvm"}, ps.ToArgs()...)

	cmd := testexec.CommandContext(ctx, "prlimit", args...)

	output, err := os.Create(filepath.Join(s.OutDir(), "crosvm.log"))
	if err != nil {
		s.Fatal("Failed to create crosvm log file: ", err)
	}
	defer output.Close()

	cmd.Stdout = output
	cmd.Stderr = output

	// Drop host caches before starting crosvm
	if err := disk.DropCaches(ctx); err != nil {
		s.Fatal("Failed to drop caches: ", err)
	}

	if err := cmd.Run(testexec.DumpLogOnError); err != nil {
		s.Fatal("Failed to run crosvm: ", err)
	}

	buf, err := ioutil.ReadFile(fioOutput)
	if err != nil {
		s.Fatal("Failed to read fio results: ", err)
	}

	results := make(map[string]interface{})
	if err := json.Unmarshal(buf, &results); err != nil {
		s.Fatal("Failed to unmarshal fio results: ", err)
	}

	perfValues := perf.NewValues()
	jobs := results["jobs"].([]interface{})
	for _, i := range jobs {
		j := i.(map[string]interface{})
		read := j["read"].(map[string]interface{})
		readBW := read["bw"].(float64)
		perfValues.Append(perf.Metric{
			Name:      "read",
			Variant:   j["jobname"].(string),
			Unit:      "KiBps",
			Direction: perf.BiggerIsBetter,
			Multiple:  true,
		}, readBW)

		write := j["write"].(map[string]interface{})
		writeBW := write["bw"].(float64)
		perfValues.Append(perf.Metric{
			Name:      "write",
			Variant:   j["jobname"].(string),
			Unit:      "KiBps",
			Direction: perf.BiggerIsBetter,
			Multiple:  true,
		}, writeBW)

		s.Logf("Jobname = %s, read bw = %v, write bw = %v", j["jobname"], readBW, writeBW)
	}
	perfValues.Save(s.OutDir())
}
