func Pmtest(ctx context.Context, s *testing.State) {
	origPmMode, err := graphics.GetPMTestState(ctx)
	if err != nil {
		s.Fatal("Failed to get original pm_test state: ", err)
	}
	s.Logf("Original pm_test state: %q", origPmMode)
	// Always try set the mode back to original.
	defer graphics.SetPMTest(ctx, origPmMode.Current)

	params := s.Param().(pmTestParam)
	mode := params.pmMode

	origSuspendMode := graphics.GetSuspendState(ctx)
	s.Log("Suspend state: ", origSuspendMode)

	//TODO: Switch to hwdep to skip instead of skipping it within test.
	if origSuspendMode != params.suspendMode {
		testing.ContextLogf(ctx, "The test is testing suspend to %v but DUT default is suspend to %v. To avoid putting DUT into unresponsive state, skip the test", params.suspendMode, origSuspendMode)
		return
	}

	inList := func(str graphics.PmTestMode, list []graphics.PmTestMode) bool {
		for _, l := range list {
			if str == l {
				return true
			}
		}
		return false
	}
	// In S0, Processors and Core are not supported.
	if origSuspendMode == graphics.SuspendS0ix && inList(mode, []graphics.PmTestMode{graphics.PmTestProcessors, graphics.PmTestCore}) {
		s.Log("Processors and core mode are not supported in S0")
		return
	}
	// Check if mode is supported.
	if !inList(mode, origPmMode.Available) {
		s.Logf("pm_test doesn't support requested mode: %v. Skipping the test", mode)
		return
	}
	if origPmMode.Current != mode {
		if err := graphics.SetPMTest(ctx, mode); err != nil {
			s.Fatal("Failed to set pm_test: ", err)
		}
	}
	// We request two consecutive suspend_resumes to ensure each cycle can be repeated.
	// In other words if the resume was unclean we give the test a chance to fail itself (and not some following test).
	out, err := testexec.CommandContext(ctx, "suspend_stress_test", "--count", fmt.Sprintf("%v", params.count), "--nopremature_wake_fatal", "--record_dmesg_dir", s.OutDir()).Output(testexec.DumpLogOnError)
	testing.ContextLog(ctx, "suspend_stress_test Output: ", string(out))
	if err != nil {
		if msg := parseSuspendStats(ctx); msg != "" {
			s.Error("suspend_stats: ", msg)
		}
		s.Fatalf("Failed to suspend to %v: %v", origSuspendMode, err)
	}
	if match := regexp.MustCompile(`(?m)^(Suspend failed.*)$`).FindSubmatch(out); len(match) > 0 {
		if msg := parseSuspendStats(ctx); msg != "" {
			s.Error("suspend_stats: ", msg)
		}
		s.Fatalf("Failed to suspend to %v: %v", origSuspendMode, string(match[1]))
	}
}

func parseSuspendStats(ctx context.Context) string {
	out, err := testexec.CommandContext(ctx, "cat", "/sys/kernel/debug/suspend_stats").Output(testexec.DumpLogOnError)
	if err != nil {
		return ""
	}
	testing.ContextLogf(ctx, "%v", string(out))

	failRegex := regexp.MustCompile(`^fail: (\d+)`)
	reasonRegex := regexp.MustCompile(`(last_failed_dev:.*)$`)
	var reasons []string
	var failed bool
	for _, line := range strings.Split(string(out), "\n") {
		if match := failRegex.FindStringSubmatch(line); match != nil {
			count, err := strconv.Atoi(match[1])
			if err != nil {
				continue
			}
			if count != 0 {
				failed = true
			}
		}
		if match := reasonRegex.FindStringSubmatch(line); match != nil && len(match) > 1 {
			reasons = append(reasons, match[1])
		}
	}

	if failed == false {
		return ""
	}
	return strings.Join(reasons, " ")
}
