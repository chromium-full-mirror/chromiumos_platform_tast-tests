package multivm

import (
	"context"
	"time"

	"go.chromium.org/tast-tests/cros/common/perf"
	"go.chromium.org/tast-tests/cros/local/crostini"
	"go.chromium.org/tast-tests/cros/local/upstart"
	"go.chromium.org/tast/core/testing"
)

func init() {
	testing.AddTest(&testing.Test{
		Func:         LogoutPerf,
		LacrosStatus: testing.LacrosVariantUnneeded,
		Desc:         "Measures time to logout while multiple VMs running",
		Contacts:     []string{"cros-virt-devices-guests@google.com", "keiichiw@google.com"},
		BugComponent: "b:1248538",
		Attr:         []string{"group:crosbolt", "crosbolt_nightly"},
		SoftwareDeps: []string{"vm_host", "chrome", "android_vm"},
		Params: []testing.Param{
			// Parameters generated by logout_perf_test.go. DO NOT EDIT.
			{
				Name:              "arc_crostini_bullseye",
				ExtraSoftwareDeps: []string{"dlc"},
				ExtraHardwareDeps: crostini.CrostiniOptimalPerf,
				Fixture:           "crostiniBullseye",
				Timeout:           7 * time.Minute,
			}, {
				Name:              "arc_crostini_bookworm",
				ExtraSoftwareDeps: []string{"dlc"},
				ExtraHardwareDeps: crostini.CrostiniOptimalPerf,
				Fixture:           "crostiniBookworm",
				Timeout:           7 * time.Minute,
			},
		},
	})
}

func LogoutPerf(ctx context.Context, s *testing.State) {
	now := time.Now()
	// Restart ui to shutdown vm service processes
	if err := upstart.RestartJob(ctx, "ui"); err != nil {
		s.Fatal("Failed to restart ui: ", err)
	}
	logoutTime := time.Since(now)

	p := perf.NewValues()
	p.Set(perf.Metric{
		Name:      "LogoutTime",
		Unit:      "milliseconds",
		Direction: perf.SmallerIsBetter,
	}, logoutTime.Seconds()*1000)

	if err := p.Save(s.OutDir()); err != nil {
		s.Error("Failed to save perf.Values: ", err)
	}
}
