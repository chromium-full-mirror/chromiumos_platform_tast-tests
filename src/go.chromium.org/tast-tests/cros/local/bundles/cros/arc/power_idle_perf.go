func PowerIdlePerf(ctx context.Context, s *testing.State) {
	const (
		iterationCount          = 60
		iterationsCountExtended = 360
		iterationDuration       = 10 * time.Second
	)
	args := s.Param().(testArgsForPowerIdlePerf)

	// Give cleanup actions a minute to run, even if we fail by exceeding our
	// deadline.
	cleanupCtx := ctx
	ctx, cancel := ctxutil.Shorten(ctx, time.Minute)
	defer cancel()

	var cr *chrome.Chrome
	hasChrome, ok := s.FixtValue().(chrome.HasChrome)
	hasarc := !ok
	if !ok {
		cr = s.FixtValue().(*arc.PreData).Chrome
		if cr == nil {
			s.Fatal("Failed to get Chrome from FixtValue")
		}
	} else {
		cr = hasChrome.Chrome()
	}

	tconn, err := cr.TestAPIConn(ctx)
	if err != nil {
		s.Fatal("Failed to connect to test API: ", err)
	}

	sup, cleanup := setup.New("power idle perf")
	defer func() {
		if err := cleanup(cleanupCtx); err != nil {
			s.Fatal("Cleanup failed: ", err)
		}
	}()

	discharge := args.setupOption == setup.ForceBatteryDischarge
	sup.Add(setup.PowerTest(ctx, tconn,
		setup.PowerTestOptions{
			Wifi:               setup.DisableWifiInterfaces,
			NightLight:         setup.DisableNightLight,
			DarkTheme:          setup.EnableLightTheme,
			UI:                 setup.DoNotChangeUI,
			Multicast:          setup.DisableMulticast,
			Ramfs:              setup.DoNotSetupRamfs,
			Powerd:             setup.DoNotChangePowerd,
			UpdateEngine:       setup.DisableUpdateEngine,
			VNC:                setup.DisableVNC,
			Avahi:              setup.DisableAvahi,
			DPTF:               setup.DisableDPTF,
			Backlight:          setup.SetBacklight, // set to default value.
			KeyboardBrightness: setup.SetKbBrightnessToZero,
			Audio:              setup.Mute,
			Bluetooth:          setup.DisableBluetoothInterfaces,
		},
		setup.NewBatteryDischarge(discharge, true /*ignoreErr*/, setup.DefaultDischargeThreshold),
	))
	if err := sup.Check(ctx); err != nil {
		s.Fatal("Setup failed: ", err)
	}

	metrics, err := perf.NewTimeline(ctx, metrics.TestMetrics(), perf.Interval(iterationDuration))
	if err != nil {
		s.Fatal("Failed to build metrics: ", err)
	}
	s.Log("Finished setup")

	// Wait until CPU is stabilized (cooled down and idle).
	cooldownTime, err := cpu.WaitUntilStabilized(ctx, cpu.IdleCoolDownConfig())
	if err != nil {
		s.Fatal("Failed to wait until CPU is stabilized: ", err)
	}

	out, err := testexec.CommandContext(ctx, "top", "-n1", "-b").Output(testexec.DumpLogOnError)
	if err == nil {
		s.Log("Saving `top` results to top.txt")
		os.WriteFile(filepath.Join(s.OutDir(), "top.txt"), []byte(out), 0644)
	}

	if hasarc {
		if err := arc.CheckNoDex2Oat(s.OutDir()); err != nil {
			s.Fatal("Failed to verify dex2oat was not running: ", err)
		}

		out, err := arc.BootstrapCommand(ctx, "/system/bin/top", "-n1", "-b").Output()
		if err == nil {
			s.Log("Saving `android-sh -c top` results to arc-top.txt")
			os.WriteFile(filepath.Join(s.OutDir(), "arc-top.txt"), []byte(out), 0644)
		}
	}

	if err := metrics.Start(ctx); err != nil {
		s.Fatal("Failed to start metrics: ", err)
	}

	if err := metrics.StartRecording(ctx); err != nil {
		s.Fatal("Failed to start recording: ", err)
	}

	duration := iterationCount * iterationDuration
	if args.extendedTest {
		duration = iterationsCountExtended * iterationDuration
	}
	// GoBigSleepLint: It's used as a measurement step which is part of the performance testing logic.
	if err := testing.Sleep(ctx, duration); err != nil {
		s.Fatal("Failed to sleep: ", err)
	}

	p, err := metrics.StopRecording(ctx)
	if err != nil {
		s.Fatal("Error while recording power metrics: ", err)
	}

	cooldownTimeMetric := perf.Metric{Name: "cooldown_time", Unit: "ms", Direction: perf.SmallerIsBetter}
	p.Set(cooldownTimeMetric, float64(cooldownTime.Milliseconds()))

	// Report memory usage.
	arcPre, ok := s.FixtValue().(*arc.PreData)
	metricRegexp := regexp.MustCompile("[^a-zA-Z0-9]")
	if ok {
		memOut, err := arcPre.ARC.Command(ctx, "cat", "/proc/meminfo").Output()
		var valMemFree int64
		var valMemTotal int64
		if err != nil {
			s.Fatal("Failed to read from /proc/meminfo: ", err)
		} else {
			scanner := bufio.NewScanner(strings.NewReader(string(memOut)))
			for scanner.Scan() {
				// Line format example: MemTotal:      14863104 kB
				line := scanner.Text()
				tokens := strings.Fields(line)
				memName := tokens[0][:len(tokens[0])-1]
				// No special characters allowed in metric names.
				metricName := metricRegexp.ReplaceAllString(memName, "_")
				metricValue := tokens[1]
				metricUnit := tokens[2]

				if metricUnit != "kB" {
					s.Fatalf("Invalid metric unit. Found %s, expected kB", metricUnit)
				}

				valueInt, err := strconv.ParseInt(metricValue, 10, 64)
				if err != nil {
					s.Fatal("Invalid metric value: ", err)
				}

				// Convert KB to bytes.
				valueBytes := valueInt * 1000

				if memName == "MemFree" {
					valMemFree = valueBytes
				} else if memName == "MemTotal" {
					valMemTotal = valueBytes
				}

				memMetric := perf.Metric{Name: "arc_mem_" + metricName, Unit: "bytes", Direction: perf.SmallerIsBetter}
				p.Set(memMetric, float64(valueBytes))
			}

			// TotalUsage = MemTotal - MemFree
			memMetric := perf.Metric{Name: "arc_mem_TotalUsage", Unit: "bytes", Direction: perf.SmallerIsBetter}
			valMemUsage := valMemTotal - valMemFree
			if valMemUsage <= 0 {
				s.Fatalf("Invalid total memory usage: total = %d, free = %d", valMemTotal, valMemFree)
			}
			p.Set(memMetric, float64(valMemUsage))
		}
	} else {
		testing.ContextLog(ctx, "ARC not running, skipping memory metrics")
	}

	if err := power.GeneratePowerLogAndSaveToCrosbolt(ctx, s.OutDir(), s.TestName(), p, nil); err != nil {
		s.Error("Failed to save and upload power metrics: ", err)
	}
}
