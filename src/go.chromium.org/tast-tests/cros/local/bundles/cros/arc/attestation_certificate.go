const (
	certTestAppApkName    = "IntegrityAPIApp.apk"
	certTesterAppName     = "IntegrityAPI"
	certTesterPackageName = "com.dynamic.integrity"
	keyAttestationTabText = "KA"

	tabLayoutID                  = ":id/tab_layout"
	devicePropCheckboxID         = ":id/include_device_properties_checkbox"
	callKeyAttestationButtonID   = ":id/request_key_attestation_button"
	keyAttestationResponseTextID = ":id/key_attestation_response_text"

	expectedVersion                         = 200
	expectedVerificationResultForTestImages = "KEY_ATTESTATION_RECORD_VERIFICATION_RESULT_OK"
	expectedBootKeyForTestImages            = "AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA="
	expectedBootStateForTestImages          = "UNVERIFIED"
	expectedSecurityLevelForTestImages      = "TRUSTED_ENVIRONMENT"
)

type rootOfTrust struct {
	VerifiedBootKey   string `json:"verifiedBootKey"`
	DeviceLocked      bool   `json:"deviceLocked"`
	VerifiedBootState string `json:"verifiedBootState"`
	VerifiedBootHash  string `json:"verifiedBootHash"`
}

type authorizationList struct {
	Purposes    *[]string    `json:"purposes"`
	Digests     *[]string    `json:"digests"`
	RootOfTrust *rootOfTrust `json:"rootOfTrust"`
}

type keyDescription struct {
	KeyAttestationVersion    uint32             `json:"keyAttestationVersion"`
	AttestationSecurityLevel string             `json:"attestationSecurityLevel"`
	KeyMintVersion           uint32             `json:"keyMintVersion"`
	KeyMasterSecurityLevel   string             `json:"keymasterSecurityLevel"`
	AttestationChallenge     string             `json:"attestationChallenge"`
	SoftwareEnforced         *authorizationList `json:"softwareEnforced"`
	HardwareEnforced         *authorizationList `json:"teeEnforced"`
}

type attestedDeviceID struct {
	Brand        string `json:"brand"`
	Product      string `json:"product"`
	Device       string `json:"device"`
	Model        string `json:"model"`
	Manufacturer string `json:"manufacturer"`
}

// keyAttestationRecord is generated by IntegrityAPI app:
// http://google3/java/com/google/android/apps/play/store/sdk/integrity/samples/integrityapi/app/src/main/java/com/dynamic/integrity/KeyAttestationRecordGenerator.java
// Schema for attestation content can be viewed at:
// https://source.android.com/docs/security/features/keystore/attestation#attestation-v200
type keyAttestationRecord struct {
	VerificationResult string            `json:"verificationResult"`
	AttestedDeviceID   *attestedDeviceID `json:"certificateAttestedDeviceId"`
	KeyDescription     *keyDescription   `json:"keyDescription"`
	AttestedKey        string            `json:"attestedKey"`
}

type attestationCertificateTestParam struct {
	enableAttestationFlag bool
}

func init() {
	testing.AddTest(&testing.Test{
		Func:     AttestationCertificate,
		Desc:     "Verify Key Attestation certificate values",
		Contacts: []string{"arc-commercial@google.com", "batoon@google.com"},
		// ChromeOS > Software > ARC++ > Commercial > Tast Tests
		BugComponent: "b:1487630",
		Attr:         []string{"group:mainline", "informational", "group:criticalstaging"},
		Timeout:      chrome.LoginTimeout + arc.BootTimeout + 60*time.Second,
		SoftwareDeps: []string{"android_vm_t", "chrome", "no_qemu"},
		HardwareDeps: hwdep.D(hwdep.MinStorage(17)), // UI Automator is flaky on low storage devices.
		VarDeps:      []string{uiCommon.GaiaPoolDefaultVarName},
		Data:         []string{certTestAppApkName},
		Params: []testing.Param{{
			Name:              "launched",
			Val:               attestationCertificateTestParam{enableAttestationFlag: false},
			ExtraSoftwareDeps: []string{"arc_attestation_launched"},
		}, {
			Name:              "not_launched",
			Val:               attestationCertificateTestParam{enableAttestationFlag: true},
			ExtraSoftwareDeps: []string{"arc_attestation_not_launched"},
		}},
	})
}

// AttestationCertificate will only pass on lab devices. It is expected to fail for DUTs used for development.
func AttestationCertificate(ctx context.Context, s *testing.State) {
	cleanupCtx := ctx
	ctx, cancel := ctxutil.Shorten(ctx, 30*time.Second)
	defer cancel()

	opts := []chrome.Option{
		chrome.ARCEnabled(),
		chrome.UnRestrictARCCPU(),
		chrome.ExtraArgs(arc.DisableSyncFlags()...),
	}
	enableAttestationFlag := s.Param().(attestationCertificateTestParam).enableAttestationFlag
	if enableAttestationFlag {
		opts = append(opts, chrome.EnableFeatures("ArcAttestation"))
	}

	cr, err := chrome.New(ctx, opts...)
	if err != nil {
		s.Fatal("Failed to connect to Chrome: ", err)
	}
	defer cr.Close(cleanupCtx)

	a, err := arc.New(ctx, s.OutDir(), cr.NormalizedUser())
	if err != nil {
		s.Fatal("Failed to start ARC: ", err)
	}
	defer a.Close(cleanupCtx)

	s.Log("Installing " + certTesterAppName)
	if err := a.Install(ctx, s.DataPath(certTestAppApkName)); err != nil {
		s.Fatal("Failed to install IntegrityAPI: ", err)
	}
	defer func(ctx context.Context) {
		s.Log("Uninstalling " + certTestAppApkName)
		if err := a.Uninstall(ctx, certTesterPackageName); err != nil {
			s.Fatal("Failed to uninstall IntegrityAPI APK: ", err)
		}
	}(cleanupCtx)

	kb, err := input.Keyboard(ctx)
	if err != nil {
		s.Fatal("Failed to get keyboard controller: ", err)
	}
	defer kb.Close(cleanupCtx)

	d, err := a.NewUIDevice(ctx)
	if err != nil {
		s.Fatal("Failed to initialize UI Automator: ", err)
	}
	defer d.Close(cleanupCtx)

	tconn, err := cr.TestAPIConn(ctx)
	if err != nil {
		s.Fatal("Failed to create test API connection: ", err)
	}
	defer faillog.DumpUITreeOnError(cleanupCtx, s.OutDir(), s.HasError, tconn)

	s.Log("Launching " + certTesterAppName)
	app, err := apputil.NewApp(ctx, kb, tconn, a, d, certTesterAppName, certTesterPackageName)
	if err != nil {
		s.Fatal("Failed to create the instance of IntegrityAPI app: ", err)
	}
	if _, err := app.Launch(ctx); err != nil {
		s.Fatal("Failed to launch IntegrityAPI app: ", err)
	}

	s.Logf("Using %s to retrieve Key Attestation record", certTesterAppName)
	result, err := retrieveRecordFromAppUI(ctx, d)
	if err != nil {
		s.Fatal("Retrieving Key Attestation record from IntegrityAPIApp failed: ", err)
	}

	s.Logf("Retrieved Key Attestation record: [%s]", result)

	s.Log("Verifying values in Key Attestation record")
	var record keyAttestationRecord
	if err = json.Unmarshal([]byte(result[strings.Index(result, "{"):]), &record); err != nil {
		s.Fatal("Failed to unmarshal the Key Attestation record: ", err)
	}
	if err = verifyKeyAttestationRecord(ctx, record); err != nil {
		s.Fatal("Failed to verify values in Key Attestation record: ", err)
	}
}

// retrieveRecordFromAppUI interacts with the IntegrityAPI app to retrieve
// the Key Attestation record and returns the record as a string.
func retrieveRecordFromAppUI(ctx context.Context, d *ui.Device) (string, error) {
	tabLayout := d.Object(ui.ID(certTesterPackageName + tabLayoutID))
	keyAttestationTab := d.Object(ui.Text(keyAttestationTabText))

	if err := tabLayout.GetChild(ctx, keyAttestationTab); err != nil {
		return "", errors.Wrap(err, "failed to get tab layout child")
	}
	if err := keyAttestationTab.WaitForExists(ctx, 5*time.Second); err != nil {
		return "", errors.Wrap(err, "failed to find Key Attestation tab")
	}
	if err := keyAttestationTab.Click(ctx); err != nil {
		return "", errors.Wrap(err, "failed to click Key Attestation tab")
	}

	devicePropCheckbox := d.Object(ui.ID(certTesterPackageName + devicePropCheckboxID))
	if err := devicePropCheckbox.WaitForExists(ctx, 5*time.Second); err != nil {
		return "", errors.Wrap(err, "failed to find checkbox to include device properties")
	}
	if err := devicePropCheckbox.Click(ctx); err != nil {
		return "", errors.Wrap(err, "failed to click checkbox to include device properties")
	}

	callKeyAttestationButton := d.Object(ui.ID(certTesterPackageName + callKeyAttestationButtonID))
	if err := callKeyAttestationButton.Click(ctx); err != nil {
		return "", errors.Wrap(err, "failed to click Call Key Attestation button")
	}

	keyAttestationResult := d.Object(ui.ID(certTesterPackageName + keyAttestationResponseTextID))

	// Wait for non-empty result from Key Attestation response text.
	var result string
	if err := testing.Poll(ctx, func(ctx context.Context) error {
		var err error
		result, err = keyAttestationResult.GetText(ctx)
		if err != nil {
			return testing.PollBreak(errors.Wrap(err, "failed to retrieve Key Attestation response text"))
		}

		if len(string(result)) == 0 {
			return errors.New("Received empty Key Attestation record")
		}
		return nil
	}, &testing.PollOptions{Interval: time.Second, Timeout: 15 * time.Second}); err != nil {
		return "", err
	}

	return string(result), nil
}

// verifyKeyAttestationRecord inspects the data within the record to validate the values
// of certain key fields and make sure other key fields are not empty or nil.
func verifyKeyAttestationRecord(ctx context.Context, record keyAttestationRecord) error {
	if record.VerificationResult != expectedVerificationResultForTestImages {
		testing.ContextLog(ctx, "This will fail on dev devices. This test must be run on lab/crosfleet")
		return errors.Errorf("unexpected verification result: %s; Expected: %s",
			record.VerificationResult, expectedVerificationResultForTestImages)
	}
	if record.AttestedDeviceID == nil {
		return errors.New("CertificateAttestedDeviceID was not found in Key Attestation record")
	}
	if len(record.AttestedKey) == 0 {
		return errors.New("AttestedKey was not found in Key Attestation record")
	}

	keyDesc := record.KeyDescription
	if keyDesc == nil {
		return errors.New("KeyDescription was not found in Key Attestation record")
	}
	if keyDesc.KeyAttestationVersion != expectedVersion {
		return errors.Errorf("incorrect Key Attestation Version: %d; Expected: %d",
			keyDesc.KeyAttestationVersion, expectedVersion)
	}
	if keyDesc.KeyMintVersion != expectedVersion {
		return errors.Errorf("incorrect KeyMint Version: %d; Expected: %d",
			keyDesc.KeyMintVersion, expectedVersion)
	}
	if keyDesc.AttestationSecurityLevel != expectedSecurityLevelForTestImages {
		return errors.Errorf("incorrect attestation security level: %s; Expected: %s",
			keyDesc.AttestationSecurityLevel, expectedSecurityLevelForTestImages)
	}
	if keyDesc.KeyMasterSecurityLevel != expectedSecurityLevelForTestImages {
		return errors.Errorf("incorrect Keymaster security level: %s; Expected: %s",
			keyDesc.KeyMasterSecurityLevel, expectedSecurityLevelForTestImages)
	}
	if len(keyDesc.AttestationChallenge) == 0 {
		return errors.New("AttestationChallenge was not found in KeyDescription")
	}
	if keyDesc.SoftwareEnforced == nil {
		return errors.New("SoftwareEnforced list was not found in KeyDescription")
	}

	hardwareEnforcedList := keyDesc.HardwareEnforced
	if hardwareEnforcedList == nil {
		return errors.New("HardwareEnforced list was not found in KeyDescription")
	}
	if len(*hardwareEnforcedList.Purposes) == 0 {
		return errors.New("Purposes in HardwareEnforced list was empty")
	}
	if len(*hardwareEnforcedList.Digests) == 0 {
		return errors.New("Digests in HardwareEnforced list was empty")
	}

	vbParams := hardwareEnforcedList.RootOfTrust
	if vbParams == nil {
		return errors.New("Root of trust was not found in HardwareEnforced list")
	}
	if vbParams.VerifiedBootKey != expectedBootKeyForTestImages {
		return errors.Errorf("incorrect verified boot key: %s; Expected: %s",
			vbParams.VerifiedBootKey, expectedBootKeyForTestImages)
	}
	if vbParams.DeviceLocked {
		return errors.New("Incorrect DeviceLocked value: true; Expected: false")
	}
	if vbParams.VerifiedBootState != expectedBootStateForTestImages {
		return errors.Errorf("incorrect verified boot state: %s; Expected: %s",
			vbParams.VerifiedBootState, expectedBootStateForTestImages)
	}
	if len(vbParams.VerifiedBootHash) == 0 {
		return errors.New("Verified Boot Hash was empty")
	}

	return nil
}
