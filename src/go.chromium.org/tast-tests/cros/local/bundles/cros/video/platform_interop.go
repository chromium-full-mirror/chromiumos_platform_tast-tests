// PlatformInterop verifies interoperability of combinations of SW/HW encoders
// and decoders.The encoder input is an uncompressed YUV file which would be
// too large to be stored, so it is produced on the fly from
// platformInteropParam.filename. The result YUV file is compressed using
// platformInteropParam.encoderCommand and the decoded using
// platformInteropParam.decoderCommand.
func PlatformInterop(ctx context.Context, s *testing.State) {
	testOpt := s.Param().(platformInteropParam)

	yuvFile, err := encoding.PrepareYUV(ctx, s.DataPath(testOpt.filename), videotype.I420, coords.NewSize(0, 0) /* placeholder size */)
	if err != nil {
		s.Fatal("Failed to prepare YUV file: ", err)
	} else if videovars.ShouldRemoveArtifacts(ctx) {
		defer os.Remove(yuvFile)
	}

	encoderCommand, encodedFile, _, err := testOpt.encoderCommandBuilder(ctx, s.TestName(), testOpt.encoderCommand, yuvFile, testOpt.size, testOpt.fps)
	if err != nil {
		s.Fatal("Failed to construct the encoder command line: ", err)
	}

	s.Log("Running: ", shutil.EscapeSlice(encoderCommand))
	_, err = platform.RunEncoderBinary(ctx, s.OutDir(), encoderCommand[0], encoderCommand[1:]...)
	if err != nil {
		s.Fatal("Failed to run binary: ", err)
	} else if videovars.ShouldRemoveArtifacts(ctx) {
		defer os.Remove(encodedFile)
	}

	// Create a temporary md5 checksum log file. This is needed for decoding.
	f, err := os.CreateTemp("", "frame_checksums.*.md5")
	if err != nil {
		s.Fatal("Failed to create md5 checksum log: ", err)
	}
	md5LogPath := f.Name()
	if err := f.Close(); err != nil {
		s.Fatal("Failed to close md5 checksum log: ", err)
	}
	defer os.Remove(md5LogPath)

	decoderCommandArgs := testOpt.decoderArgsBuilder(ctx, encodedFile)
	/*md5Arg := platform.MD5Args(testOpt.decoderCommand, md5LogPath)
	if md5Arg != nil {
		decoderCommandArgs = append(decoderCommandArgs, md5Arg...)
	}*/
	decoderCommandArgs = append(decoderCommandArgs, platform.MD5Args(testOpt.decoderCommand, md5LogPath)...)
	if err != nil {
		s.Fatal("Failed to construct the decoder command line: ", err)
	}

	s.Logf("Running: %s %s ", testOpt.decoderCommand, shutil.EscapeSlice(decoderCommandArgs))
	_, err = platform.RunEncoderBinary(ctx, s.OutDir(), testOpt.decoderCommand, decoderCommandArgs...)
	if err != nil {
		s.Fatal("Failed to run binary: ", err)
	}

	// It testOpt.referenceSWDecoder is not specified, we don't need to compare
	// the generated MD5SUM values with those generated by a reference decoder
	// implementation.
	if testOpt.referenceSWDecoder == nil {
		return
	}
	actualMD5SUM, err := os.ReadFile(md5LogPath)
	if err != nil {
		s.Fatal("Failed to open md5 checksum log: ", err)
	}
	actualMD5SUMs := strings.Split(strings.TrimSpace(string(actualMD5SUM)), "\n")
	referenceMD5SUMs, err := testOpt.referenceSWDecoder(encodedFile)
	if err != nil {
		s.Fatal("Failed generating reference frame hashes: ", err)
	}

	// Find the intersection of actualMD5SUMs and referenceMD5SUMs.
	if len(actualMD5SUMs) != len(referenceMD5SUMs) {
		s.Fatalf("Decoded frame number incorrect. Expected %d, got %d", len(referenceMD5SUMs), len(actualMD5SUMs))
	}

	const maxFrameMismatches = 5
	var count int
	for i, ref := range referenceMD5SUMs {
		if actualMD5SUMs[i] == ref {
			continue
		}
		count++
		if count <= maxFrameMismatches {
			s.Errorf("Frame %d MD5SUM mismatch, got :%s, wanted %s", i, actualMD5SUMs[i], ref)
		}
	}
	if count > 0 {
		s.Fatalf("%d mismatched hashes", count)
	}
}

func genMD5AOM(file string) ([]string, error) {
	return genMD5VPXInternal(file, "aomdec")
}

func genMD5VPX(file string) ([]string, error) {
	return genMD5VPXInternal(file, "vpxdec")
}

func genMD5VPXInternal(file, decBinary string) ([]string, error) {
	// -o option is necessary for libvpx to output each frame, and with --md5
	// the md5 of each frame is output but a frame file is not created.
	out, err := exec.Command(decBinary, "-o", "output%w_%h_%4.yuv", "--i420", "--md5", file).Output()
	if err != nil {
		return []string{}, errors.Wrap(err, "failed executing vpxdec")
	}

	// Example output format:
	// a6ddd21f5f4e7424b6e7a1f2925fb33b  output320_240_0001.yuv
	// 41c77adcfd29abfaad62a057855adeaa  output320_240_0002.yuv
	// afdb44531614034e4a4a90c805a5d3b1  output320_240_0003.yuv
	var md5s []string
	for _, l := range strings.Split(strings.TrimSpace(string(out)), "\n") {
		if len(l) == 0 {
			continue
		}

		md5 := strings.Fields(l)[0]
		if len(md5) != 32 {
			return []string{}, errors.Errorf("invalid md5 length: %s", md5)
		}

		md5s = append(md5s, md5)
	}
	return md5s, nil
}

func genMD5FFMPEG(file string) ([]string, error) {
	out, err := exec.Command("ffmpeg", "-i", file, "-noautoscale", "-f", "framemd5", "-").Output()
	if err != nil {
		return []string{}, errors.Wrap(err, "failed executing ffmpeg")
	}

	// Example output format:
	// 0,          0,          0,        1,   115200, a5dad6170eb13fc5cbc6fe3511d44053
	// 0,          1,          1,        1,   115200, e056362baaf13dd0f888e67a681ab381
	// 0,          2,          2,        1,   115200, ee0c33d2b92e0443ca5770bd0c56911f
	var md5s []string
	for _, l := range strings.Split(strings.TrimSpace(string(out)), "\n") {
		matches := regExpFFMPEGMD5.FindAllStringSubmatch(l, -1)
		if len(matches) != 1 {
			continue
		}

		md5 := matches[0][1]
		if len(md5) != 32 {
			return []string{}, errors.Errorf("invalid md5 length: %s", md5)
		}

		md5s = append(md5s, md5)
	}
	return md5s, nil
}
