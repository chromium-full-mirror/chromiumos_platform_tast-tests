// verifyInstallAttributes verifies the contents of current install_attributes with the base version.
func verifyInstallAttributes(ctx context.Context, cryptohome *hwsec.CryptohomeClient, config *util.CrossVersionLoginConfig) error {
	for name, expectedValue := range config.InstallAttrs {
		value, err := cryptohome.InstallAttributesGet(ctx, name)
		if err != nil {
			return errors.Wrapf(err, "failed to get install attributes for %s", name)
		}
		if value != expectedValue {
			return errors.Errorf("mismatched install attributes for %s. expected: %s, found: %s", name, expectedValue, value)
		}
	}
	return nil
}

// testInstallAttributes verifies that the install attributes are consistent across migration.
func testInstallAttributes(ctx context.Context, config *util.CrossVersionLoginConfig) error {
	cmdRunner := hwseclocal.NewCmdRunner()
	helper, err := hwseclocal.NewHelper(cmdRunner)
	if err != nil {
		return errors.Wrap(err, "failed to create the helper instance")
	}
	cryptohome := helper.CryptohomeClient()
	tpmManager := helper.TPMManagerClient()
	dc := helper.DaemonController()

	status, err := tpmManager.RuntimeSelectionSupportStatus(ctx)
	if err != nil {
		return errors.Wrap(err, "failed to fetch supported features")
	}
	if !status {
		// Populate lockbox.nvram. For tpm_dynamic, it is handled in lockbox-cache-manager.
		if _, err := tpmManager.ReadSpaceToFile(ctx, util.NvramTpm2Index, util.LockboxNvramPath, "" /*no password*/); err != nil {
			return errors.Wrap(err, "failed to read nvram space")
		}
	}

	// Restart lockbox-cache job.
	if err := dc.Restart(ctx, hwsec.LockboxCacheJob); err != nil {
		return errors.Wrap(err, "failed to restart lockbox-cache job")
	}

	// Restart device_management daemon to restore the install_attributes state.
	if err := dc.Restart(ctx, hwsec.DeviceManagementDaemon); err != nil {
		return errors.Wrap(err, "failed to restart device_managementd")
	}

	// Verify consistency of the install-attributes contents.
	if err := verifyInstallAttributes(ctx, cryptohome, config); err != nil {
		return errors.Wrap(err, "failed to verify the consistency of install attributes content")
	}

	return nil
}

func CrossVersionInstallAttributes(ctx context.Context, s *testing.State) {
	fixtureData := s.FixtValue().(*fixture.CrossVersionLoginFixture)
	for _, config := range fixtureData.ConfigList {
		if len(config.InstallAttrs) == 0 {
			continue
		}
		if err := testInstallAttributes(ctx, &config); err != nil {
			s.Fatal("Failed to test install attributes: ", err)
		}
	}
}
