func AppVscodeWindowOperations(ctx context.Context, s *testing.State) {
	tconn := s.FixtValue().(crostini.FixtureData).Tconn
	keyboard := s.FixtValue().(crostini.FixtureData).KB
	d := s.FixtValue().(crostini.FixtureData).Differ()
	cont := s.FixtValue().(crostini.FixtureData).Cont
	op := s.Param().(apps.WindowOperation)

	cleanupCtx := ctx
	ctx, cancel := ctxutil.Shorten(ctx, 5*time.Second)
	defer cancel()
	handler := faillog.DumpUITreeWithScreenshotHandler(cleanupCtx, tconn, "ui_tree")
	s.AttachErrorHandlers(handler, handler)

	if err := apps.InitialiseVSCode(ctx, apps.VSCode, cont, keyboard, tconn); err != nil {
		s.Fatal("Failed to configure VS Code: ", err)
	}

	if err := apps.TestWindowOperation(ctx, op, apps.VSCode.AppName, apps.VSCode.AppName, "File", keyboard, tconn, d, false); err != nil {
		s.Fatal("Window operation failed: ", err)
	}
}
