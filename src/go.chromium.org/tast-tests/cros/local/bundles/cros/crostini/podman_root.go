func init() {
	testing.AddTest(&testing.Test{
		Func:         PodmanRoot,
		LacrosStatus: testing.LacrosVariantUnneeded,
		Desc:         "Tests running a Podman container in Crostini",
		Contacts:     []string{"clumptini+oncall@google.com"},
		SoftwareDeps: []string{"chrome", "vm_host"},
		Attr:         []string{"group:mainline"},
		BugComponent: "b:1122570",
		Data:         []string{"hello-world-amd64.tar", "hello-world-arm64.tar"},
		Params: []testing.Param{
			// Parameters generated by params_test.go. DO NOT EDIT.
			{
				Name:              "bookworm_stable",
				ExtraSoftwareDeps: []string{"dlc"},
				ExtraHardwareDeps: crostini.CrostiniAppStable,
				Fixture:           "crostiniBookwormLargeContainer",
				Timeout:           15 * time.Minute,
			}, {
				Name:              "bookworm_unstable",
				ExtraAttr:         []string{"informational"},
				ExtraSoftwareDeps: []string{"dlc"},
				ExtraHardwareDeps: crostini.CrostiniAppUnstable,
				Fixture:           "crostiniBookwormLargeContainer",
				Timeout:           15 * time.Minute,
			},
		},
	})
}

func PodmanRoot(ctx context.Context, s *testing.State) {
	cont := s.FixtValue().(crostini.FixtureData).Cont

	if err := cont.PushFile(ctx, s.DataPath(oci.ImageForArch(oci.HelloWorldImage)), oci.HelloWorldImage); err != nil {
		s.Fatal("Failed to push container image: ", err)
	}

	cmd := cont.Command(ctx, "sudo", "podman", "load", "-i", oci.HelloWorldImage)
	if _, stderr, err := cmd.SeparatedOutput(); err != nil {
		s.Logf("stderr: %q", string(stderr))
		s.Fatal("Failed to load container image: ", err)
	}

	cmd = cont.Command(ctx, "sudo", "podman", "run", "--pull=never", oci.HelloWorldContainer)
	out, stderr, err := cmd.SeparatedOutput()
	if err != nil {
		s.Logf("stderr: %q", string(stderr))
		s.Fatal("Failed to run container: ", err)
	}

	if !strings.Contains(string(out), oci.HelloWorldString) {
		s.Fatal("Container did not run correctly")
	}
}
