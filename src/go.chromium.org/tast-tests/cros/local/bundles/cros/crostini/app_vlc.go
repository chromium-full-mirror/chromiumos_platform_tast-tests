const testVideo = "vlc_test_video.mp4"

func init() {
	testing.AddTest(&testing.Test{
		Func:         AppVLC,
		LacrosStatus: testing.LacrosVariantUnneeded,
		Desc:         "Opens VLC from launcher",
		Contacts:     []string{"clumptini+oncall@google.com"},
		Attr:         []string{"group:mainline", "group:crostini_app_cq", "informational"},
		Vars:         screenshot.ScreenDiffVars,
		SoftwareDeps: []string{"chrome", "vm_host"},
		Data:         []string{testVideo},
		BugComponent: "b:1122570",
		Params: []testing.Param{
			// Parameters generated by params_test.go. DO NOT EDIT.
			{
				Name:              "bookworm_clamshell_stable",
				ExtraSoftwareDeps: []string{"crostini_app", "dlc"},
				ExtraHardwareDeps: crostini.CrostiniAppStable,
				Fixture:           "crostiniBookwormLargeContainerClamshell",
				Timeout:           15 * time.Minute,
			},
		},
	})
}

const (
	sampleRate           = 48000
	sampleDuration       = 30 * time.Second
	audioChannels        = 2
	allowedErrorFraction = 0.1
	freqTolerance        = 20
)

var expectedFreq = [audioChannels]float64{220, 440}

func AppVLC(ctx context.Context, s *testing.State) {
	tconn := s.FixtValue().(crostini.FixtureData).Tconn
	cr := s.FixtValue().(crostini.FixtureData).Chrome
	keyboard := s.FixtValue().(crostini.FixtureData).KB
	cont := s.FixtValue().(crostini.FixtureData).Cont
	d := s.FixtValue().(crostini.FixtureData).Differ()

	// Use a shortened context for test operations to reserve time for cleanup.
	cleanupCtx := ctx
	ctx, cancel := ctxutil.Shorten(ctx, 5*time.Second)
	defer cancel()
	handler := faillog.DumpUITreeWithScreenshotHandler(cleanupCtx, tconn, "ui_tree")
	s.AttachErrorHandlers(handler, handler)

	ui := uiauto.New(tconn)

	unload, err := audio.LoadAloop(ctx)
	if err != nil {
		s.Fatal("Failed to load loopback audio device: ", err)
	}
	defer unload(cleanupCtx)

	if err := audio.SetupLoopback(ctx, cr, s.OutDir(), s.HasError); err != nil {
		s.Fatal("Failed to set up loopback audio device: ", err)
	}

	if err := cont.PushFile(ctx, s.DataPath(testVideo), testVideo); err != nil {
		s.Fatal("Failed to push file to container: ", err)
	}

	homeDir, err := cont.GetHomeDir(ctx)
	if err != nil {
		s.Fatal("Failed to find user home directory in container: ", err)
	}

	s.Log("Launching VLC")

	if err := uiauto.Retry(3,
		launcher.SearchAndLaunchWithQuery(tconn, keyboard, "VLC media player", "VLC media player"),
	)(ctx); err != nil {
		s.Fatal("Failed to launch VLC: ", err)
	}

	mainWindow := nodewith.NameRegex(regexp.MustCompile(`.*VLC media player`)).Role(role.Window).HasClass("RootView")

	popupWindow := nodewith.Name("Privacy and Network Access Policy").Role(role.Window).HasClass("RootView")
	popupWindowClose := nodewith.Ancestor(popupWindow).Name("Close").Focusable()

	if err := uiauto.Combine("verify VLC",
		ui.WithTimeout(2*time.Minute).WaitUntilExists(mainWindow),
		ui.WithTimeout(10*time.Second).WaitUntilExists(popupWindowClose),
		ui.DoDefault(popupWindowClose),
		ui.WithTimeout(10*time.Second).WaitUntilGone(popupWindow),
		screenshot.DiffWindow(ctx, d, "VLC", screenshot.Retries(5)),
	)(ctx); err != nil {
		s.Fatal("Failed to capture VLC window: ", err)
	}

	s.Log("Starting test file playback")

	if err := cont.Command(ctx, "dbus-send", "--print-reply", "--session", "--dest=org.mpris.MediaPlayer2.vlc", "/org/mpris/MediaPlayer2",
		"org.mpris.MediaPlayer2.Player.OpenUri", fmt.Sprintf("string:file://%s", path.Join(homeDir, testVideo))).Run(testexec.DumpLogOnError); err != nil {
		s.Fatal("Failed to start video: ", err)
	}

	streams, err := crastestclient.WaitForStreams(ctx, 10*time.Second)
	if err != nil {
		s.Fatal("Failed to wait for audio streams from VLC: ", err)
	}
	s.Log("Found audio streams: ", streams)
	s.Log("Capturing audio playback")

	recordingFile := "/tmp/vlc_recording.raw"

	if err := crastestclient.CaptureFileCommand(
		ctx, recordingFile, int(sampleDuration.Seconds()),
		audioChannels, sampleRate).Run(testexec.DumpLogOnError); err != nil {

		s.Fatal("Failed to capture audio streams from VLC: ", err)
	}

	// Convert the raw audio file to a non-raw format so it's easier to examine.
	if err := testexec.CommandContext(
		ctx, "ffmpeg", "-f", "s16le", "-ar", strconv.Itoa(sampleRate), "-ac", strconv.Itoa(audioChannels),
		"-i", recordingFile, filepath.Join(s.OutDir(), "vlc_recording.wav")).Run(testexec.DumpLogOnError); err != nil {

		s.Fatal("Failed to convert raw audio to WAV: ", err)
	}

	s.Log("Capturing video playback")

	// Pause playback and move to a fixed timestamp so the screenshots are consistent.
	if err := cont.Command(ctx, "dbus-send", "--print-reply", "--session", "--dest=org.mpris.MediaPlayer2.vlc", "/org/mpris/MediaPlayer2",
		"org.mpris.MediaPlayer2.Player.Pause").Run(testexec.DumpLogOnError); err != nil {
		s.Fatal("Failed to pause playback: ", err)
	}

	metadata, err := cont.Command(ctx, "dbus-send", "--print-reply", "--session", "--dest=org.mpris.MediaPlayer2.vlc", "/org/mpris/MediaPlayer2",
		"org.freedesktop.DBus.Properties.Get", "string:org.mpris.MediaPlayer2.Player", "string:Metadata").Output(testexec.DumpLogOnError)
	if err != nil {
		s.Fatal("Failed to get video player metadata: ", err)
	}

	matches := regexp.MustCompile(`object path "([a-zA-Z0-9/]+)"`).FindAllStringSubmatch(string(metadata), -1)
	if len(matches) != 1 || len(matches[0]) != 2 {
		s.Fatal("Failed to parse metadata output: ", metadata)
	}

	objpath := matches[0][1]

	if err := cont.Command(ctx, "dbus-send", "--print-reply", "--session", "--dest=org.mpris.MediaPlayer2.vlc", "/org/mpris/MediaPlayer2",
		"org.mpris.MediaPlayer2.Player.SetPosition", fmt.Sprintf("objpath:%s", objpath), "int64:30000000").Run(testexec.DumpLogOnError); err != nil {
		s.Fatal("Failed to set video timestamp: ", err)
	}

	if err := screenshot.DiffWindow(ctx, d, "VLC with video", screenshot.Retries(5), screenshot.RetryInterval(500*time.Millisecond))(ctx); err != nil {
		s.Fatal("Failed to capture VLC playing video: ", err)
	}

	s.Log("Closing VLC")

	if err := cont.Command(ctx, "dbus-send", "--print-reply", "--session", "--dest=org.mpris.MediaPlayer2.vlc", "/org/mpris/MediaPlayer2",
		"org.mpris.MediaPlayer2.Quit").Run(testexec.DumpLogOnError); err != nil {
		s.Fatal("Failed to close VLC: ", err)
	}

	if err := ui.WithTimeout(10 * time.Second).WaitUntilGone(mainWindow)(ctx); err != nil {
		s.Fatal("VLC window still present: ", err)
	}
}
