func CloseTerminalTabsAndWindow(ctx context.Context, s *testing.State) {
	tconn := s.FixtValue().(crostini.FixtureData).Tconn
	kb := s.FixtValue().(crostini.FixtureData).KB
	cont := s.FixtValue().(crostini.FixtureData).Cont

	ui := uiauto.New(tconn).WithInterval(500 * time.Millisecond)

	// Use a shortened context for test operations to reserve time for cleanup.
	cleanupCtx := ctx
	ctx, cancel := ctxutil.Shorten(ctx, 5*time.Second)
	defer cancel()

	handler := faillog.DumpUITreeWithScreenshotHandler(cleanupCtx, tconn, "ui_tree")
	s.AttachErrorHandlers(handler, handler)

	// Open Terminal app.
	terminalApp, err := terminalapp.Launch(ctx, tconn)
	if err != nil {
		s.Fatal("Failed to open Terminal app: ", err)
	}

	if err := uiauto.Combine("open two new tabs",
		ui.LeftClickUntil(nodewith.ClassName("NewTabButton"), terminalApp.WaitForPrompt()),
		ui.LeftClickUntil(nodewith.ClassName("NewTabButton"), terminalApp.WaitForPrompt()),
		terminalApp.WaitForTabsCount(4 /*nonTmuxTabs*/, 0 /*tmuxTabs*/),
	)(ctx); err != nil {
		s.Fatal("Failed to open new tabs: ", err)
	}

	// Drag the Terminal window to the new location and record it for future verification.
	srcLoc, err := ui.Location(ctx, terminalapp.RootWindow)
	if err != nil {
		s.Fatal("Failed to get terminal window location before move: ", err)
	}
	srcPoint := coords.Point{X: srcLoc.TopLeft().X + 1, Y: srcLoc.TopLeft().Y + 1}
	targetPoint := coords.Point{X: srcPoint.X / 2, Y: srcPoint.Y / 2}
	if err := mouse.Drag(tconn, srcPoint, targetPoint, time.Second)(ctx); err != nil {
		s.Fatal("Failed to drag the Terminal window to the new position: ", err)
	}
	lastLoc, err := ui.Location(ctx, terminalapp.RootWindow)
	if err != nil {
		s.Fatal("Failed to get terminal window location after move: ", err)
	}

	// Close all the tabs through different ways:
	// 1. Click close button on a tab.
	// 2. Press Ctrl+d.
	// 3. Click "Shut down Linux" from context menu on shelf.
	if err := uiauto.Combine("close all tabs",
		terminalApp.ClickNthTabCloseButton(1),
		terminalApp.WaitForTabsCount(3 /*nonTmuxTabs*/, 0 /*tmuxTabs*/),
		terminalApp.ClickNthTabUntilNodeExists(1, terminalapp.Prompt),
		kb.AccelAction("Ctrl+d"),
		terminalApp.WaitForTabsCount(2 /*nonTmuxTabs*/, 0 /*tmuxTabs*/),
		terminalApp.ShutdownCrostini(cont),
	)(ctx); err != nil {
		s.Fatal("Failed to close tabs and shutdown Crostini: ", err)
	}

	// Open Terminal app again.
	_, err = terminalapp.Launch(ctx, tconn)
	if err != nil {
		s.Fatal("Failed to open Terminal app: ", err)
	}

	// Get the location of the Terminal window and verify it.
	newLoc, err := ui.Location(ctx, terminalapp.RootWindow)
	if err != nil {
		s.Fatal("Failed to find terminal window: ", err)
	}
	if lastLoc.Left != newLoc.Left || lastLoc.Top != newLoc.Top ||
		lastLoc.Width != newLoc.Width || lastLoc.Height != newLoc.Height {
		s.Fatalf("Failed to veriy the new location of thee Terminal app, got %s, want %s", newLoc, lastLoc)
	}

	// The close button of a window is only available in clamshell mode.
	revert, err := devicemode.EnsureDeviceMode(ctx, tconn, devicemode.ClamshellMode)
	if err != nil {
		s.Fatal("Failed to ensure in clamshell mode: ", err)
	}
	defer revert(cleanupCtx)

	closeButton := nodewith.Name("Close").ClassName("FrameCaptionButton")
	if err := ui.LeftClickUntil(closeButton, ui.WithTimeout(time.Minute).WaitUntilGone(terminalapp.RootWindow))(ctx); err != nil {
		s.Fatal("Failed to close the Terminal window through clicking the close button on the window: ", err)
	}
}
