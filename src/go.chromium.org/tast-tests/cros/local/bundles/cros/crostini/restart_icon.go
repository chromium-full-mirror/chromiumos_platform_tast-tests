func init() {
	testing.AddTest(&testing.Test{
		Func:         RestartIcon,
		Desc:         "Tests that we can shut down and restart crostini through clicking the Terminal icon on launcher",
		Contacts:     []string{"clumptini+oncall@google.com"},
		Attr:         []string{"group:mainline"},
		SoftwareDeps: []string{"chrome", "vm_host"},
		BugComponent: "b:1122570",
		Params: []testing.Param{
			// Parameters generated by params_test.go. DO NOT EDIT.
			{
				Name:              "bookworm_stable",
				ExtraSoftwareDeps: []string{"dlc"},
				ExtraHardwareDeps: crostini.CrostiniOptimalPerf,
				Fixture:           "crostiniBookworm",
				Timeout:           7 * time.Minute,
			}, {
				Name:              "baguette_stable",
				ExtraHardwareDeps: crostini.CrostiniOptimalPerf,
				Fixture:           fixture.BaguettePolicy,
				Timeout:           7 * time.Minute,
			},
		},
	})
}

func RestartIcon(ctx context.Context, s *testing.State) {
	pre := s.FixtValue().(crostini.FixtureData)
	cont := pre.Cont
	tconn := pre.Tconn

	// Use a shortened context for test operations to reserve time for cleanup.
	cleanupCtx := ctx
	ctx, cancel := ctxutil.Shorten(ctx, 5*time.Second)
	defer cancel()

	handler := faillog.DumpUITreeWithScreenshotHandler(cleanupCtx, tconn, "ui_tree")
	s.AttachErrorHandlers(handler, handler)

	terminalApp, err := terminalapp.Launch(ctx, tconn)
	if err != nil {
		s.Fatal("Failed to launch terminal: ", err)
	}

	if err := terminalApp.ShutdownCrostini(cont)(ctx); err != nil {
		s.Fatal("Failed to shutdown crostini: ", err)
	}

	_, err = terminalapp.LaunchThroughIcon(ctx, tconn)
	if err != nil {
		s.Fatal("Failed to launch terminal after shutdown: ", err)
	}

	if strings.Contains(s.TestName(), "baguette") {
		if err = apps.Close(ctx, tconn, apps.Terminal.ID); err != nil {
			s.Fatal("Failed to exit Terminal window: ", err)
		}
	}
}
