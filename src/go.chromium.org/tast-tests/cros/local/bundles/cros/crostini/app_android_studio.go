// android-studio-linux.tar.gz is the Android Studio download for Linux from
// developer.android.com.
// android-studio-sdk.tar.gz is produced using sdkmanager:
// $ sdkmanager --sdk_root=Android/Sdk build-tools\;33.0.2 platforms\;android-33 platform-tools
// $ tar --numeric-owner -cf "android-studio-sdk-$(date +%Y%m%d).tar.gz" Android
// sdkmanager can also be downloaded from developer.android.com.

func init() {
	testing.AddTest(&testing.Test{
		Func:         AppAndroidStudio,
		Desc:         "Opens Android Studio from terminal and performs UI interactions to create new project",
		Contacts:     []string{"clumptini+oncall@google.com"},
		Attr:         []string{"group:mainline", "group:crostini_app_cq"},
		SoftwareDeps: []string{"chrome", "vm_host", "amd64"},
		VarDeps:      uidetection.UIDetectionVars,
		// b/238714120: kohaku performance is insufficient
		HardwareDeps: hwdep.D(hwdep.SkipOnModel("kohaku")),
		BugComponent: "b:1122570",
		Data:         []string{"android-studio-linux.tar.gz", "android-studio-sdk.tar.gz"},
		Params: []testing.Param{
			// Parameters generated by params_test.go. DO NOT EDIT.
			{
				Name:              "bookworm_clamshell_stable",
				ExtraSoftwareDeps: []string{"crostini_app", "dlc"},
				ExtraHardwareDeps: crostini.CrostiniAppStable,
				Fixture:           "crostiniBookwormLargeContainerClamshell",
				Timeout:           15 * time.Minute,
			},
		},
	})
}

func AppAndroidStudio(ctx context.Context, s *testing.State) {
	tconn := s.FixtValue().(crostini.FixtureData).Tconn
	keyboard := s.FixtValue().(crostini.FixtureData).KB
	cont := s.FixtValue().(crostini.FixtureData).Cont

	// Use a shortened context for test operations to reserve time for cleanup.
	cleanupCtx := ctx
	ctx, cancel := ctxutil.Shorten(ctx, 5*time.Second)
	defer cancel()

	for _, file := range []string{"android-studio-linux.tar.gz", "android-studio-sdk.tar.gz"} {
		if err := cont.PushFile(ctx, s.DataPath(file), file); err != nil {
			s.Fatalf("Failed to push %q: %v", file, err)
		}

		if err := cont.Command(ctx, "tar", "xf", file).Run(testexec.DumpLogOnError); err != nil {
			s.Fatalf("Failed to extract %q: %v", file, err)
		}

		if err := cont.Command(ctx, "rm", "-f", file).Run(testexec.DumpLogOnError); err != nil {
			s.Fatalf("Failed to delete %q: %v", file, err)
		}
	}

	// Disable container networking so Android Studio cannot get any updates.
	if err := cont.Command(ctx, "sudo", "ifdown", "eth0").Run(testexec.DumpLogOnError); err != nil {
		s.Fatal("Failed to bring eth0 down: ", err)
	}

	stdout, err := os.Create(filepath.Join(s.OutDir(), "android_studio_stdout.txt"))
	if err != nil {
		s.Fatal("Failed to create stdout log file: ", err)
	}
	defer func() {
		if err := stdout.Close(); err != nil {
			s.Log("Failed to close stdout log file: ", err)
		}
	}()

	stderr, err := os.Create(filepath.Join(s.OutDir(), "android_studio_stderr.txt"))
	if err != nil {
		s.Fatal("Failed to create stderr log file: ", err)
	}
	defer func() {
		if err := stderr.Close(); err != nil {
			s.Log("Failed to close stderr log file: ", err)
		}
	}()

	cmd := cont.Command(ctx, "android-studio/bin/studio.sh")
	cmd.Stdout = stdout
	cmd.Stderr = stderr

	if err := cmd.Start(); err != nil {
		s.Fatal("Failed to start Android Studio: ", err)
	}
	defer func() {
		// Stop Android Studio by stopping all java processes.
		if err := cont.Command(cleanupCtx, "killall", "java").Run(testexec.DumpLogOnError); err != nil {
			s.Log("Failed to stop java: ", err)
		}

		if err := cmd.Wait(); err != nil {
			s.Log("Android Studio exited: ", err)
		}
	}()

	handler := faillog.DumpUITreeWithScreenshotHandler(cleanupCtx, tconn, "ui_tree")
	s.AttachErrorHandlers(handler, handler)

	androidWindow := nodewith.NameStartingWith("Import Android Studio Settings").Role(role.Window).First()
	splashWindow := nodewith.Name("splash").Role(role.Window).First()
	newProjectWindow := nodewith.NameStartingWith("My Application").Role(role.Window).First()
	setupWizardWindow := nodewith.NameStartingWith("Android Studio Setup Wizard").Role(role.Window).First()
	newProjectDialog := nodewith.NameStartingWith("New Project").Role(role.Window).First()
	nextButton := uidetection.Word("Next")
	finishButton := uidetection.Word("Finish")
	analyticsText := uidetection.TextBlock(strings.Split("Allow Google", " "))
	firstRunText := uidetection.TextBlock(strings.Split("First Run", " "))
	ud := uidetection.NewDefault(tconn).WithScreenshotResizing()
	if err := uiauto.NamedCombine("Create a new project with defaults",
		uiauto.New(tconn).WithTimeout(30*time.Second).WaitUntilExists(androidWindow),
		// On cold startup, the splash screen window may be mapped on top of the
		// "Import Android Studio Settings" dialog and visually occlude it,
		// preventing UI detection from finding the "OK" button. Wait for the
		// splash window to be gone.
		uiauto.New(tconn).WithTimeout(15*time.Second).WaitUntilGone(splashWindow),
		// Two-letter words normally need an exact match.
		ud.LeftClick(uidetection.Word("O?K", uidetection.RegexMode(true)).First()),
		// The analytics consent dialog is flaky. Look for the body
		// text and use keyboard to dismiss as the buttons may be
		// off-screen.
		// The initialization process may take longer than the default timeout 60s.
		ud.WithTimeout(2*time.Minute).WaitUntilExists(analyticsText),
		uiauto.New(tconn).WithTimeout(time.Minute).RetryUntil(
			keyboard.AccelAction("esc"),
			ud.Gone(analyticsText),
		),
		// Dismiss the dialog warning about no network.
		ud.WaitUntilExists(firstRunText),
		ud.LeftClick(uidetection.Word("Cancel").First()),
		ud.WaitUntilGone(firstRunText),
		ud.LeftClick(nextButton.WithinA11yNode(setupWizardWindow)),
		ud.WaitUntilExists(uidetection.TextBlock(strings.Split("Install Type", " "), uidetection.MaxEditDistance(2)).WithinA11yNode(setupWizardWindow)),
		ud.LeftClick(nextButton.WithinA11yNode(setupWizardWindow)),
		ud.WaitUntilExists(uidetection.TextBlock(strings.Split("Select UI Theme", " ")).WithinA11yNode(setupWizardWindow)),
		ud.LeftClick(nextButton.WithinA11yNode(setupWizardWindow)),
		ud.WaitUntilExists(uidetection.TextBlock(strings.Split("Verify Setting", " ")).WithinA11yNode(setupWizardWindow)),
		ud.LeftClick(nextButton.WithinA11yNode(setupWizardWindow)),
		ud.WaitUntilExists(uidetection.TextBlock(strings.Split("Emulator Settings", " ")).WithinA11yNode(setupWizardWindow)),
		ud.LeftClick(finishButton.WithinA11yNode(setupWizardWindow)),
		ud.WaitUntilExists(uidetection.TextBlock(strings.Split("SDK is up to date", " ")).WithinA11yNode(setupWizardWindow)),
		ud.LeftClick(finishButton.WithinA11yNode(setupWizardWindow)),
		ud.WaitUntilExists(uidetection.TextBlock(strings.Split("Welcome to Android Studio", " "))),
		// Activate the "New Project" button. The text label is not clickable.
		uiauto.New(tconn).WithTimeout(time.Minute).RetryUntil(
			keyboard.AccelAction("space"),
			ud.Exists(uidetection.Word("Templates").WithinA11yNode(newProjectDialog)),
		),
		ud.LeftClick(nextButton.WithinA11yNode(newProjectDialog)),
		// Use ImmediateScreenshot to avoid issues with blinking cursors on the following screen.
		ud.WithScreenshotStrategy(uidetection.ImmediateScreenshot).WaitUntilExists(uidetection.TextBlock(strings.Split("Empty Activity", " ")).First()),
		ud.WithScreenshotStrategy(uidetection.ImmediateScreenshot).LeftClick(finishButton.WithinA11yNode(newProjectDialog)),
		uiauto.New(tconn).WithTimeout(time.Minute).WaitUntilExists(newProjectWindow),
		crostini.TakeAppScreenshot("android_studio"),
	)(ctx); err != nil {
		s.Fatal("Failed to create a new project with defaults: ", err)
	}

	//TODO(jinrongwu): UI test on android studio code.
}
