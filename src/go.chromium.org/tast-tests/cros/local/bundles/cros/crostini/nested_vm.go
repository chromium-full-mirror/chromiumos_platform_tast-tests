func init() {
	testing.AddTest(&testing.Test{
		Func:         NestedVM,
		Desc:         "Test that /dev/kvm is present and basic functionality works",
		Contacts:     []string{"clumptini+oncall@google.com"},
		SoftwareDeps: []string{"chrome", "vm_host", "untrusted_vm", "amd64"},
		Attr:         []string{"group:mainline"},
		// The build_image script strips out .c files, so we
		// have to use a different extension here.
		Data:         []string{"kvm_test.c-bypass-mask"},
		BugComponent: "b:1122570",
		Params: []testing.Param{
			// Parameters generated by params_test.go. DO NOT EDIT.
			{
				Name:              "bookworm_stable",
				ExtraSoftwareDeps: []string{"dlc"},
				ExtraHardwareDeps: crostini.CrostiniOptimalPerf,
				Fixture:           "crostiniBookworm",
				Timeout:           7 * time.Minute,
			}, {
				Name:              "baguette_stable",
				ExtraHardwareDeps: crostini.CrostiniOptimalPerf,
				Fixture:           fixture.BaguettePolicy,
				Timeout:           7 * time.Minute,
			},
		},
	})
}

func NestedVM(ctx context.Context, s *testing.State) {
	cont := s.FixtValue().(crostini.FixtureData).Cont

	ver, _, err := sysutil.KernelVersionAndArch()
	if err != nil {
		s.Fatal("Failed to get kernel version and arch: ", err)
	}

	if ver.Is(5, 10) || ver.Is(5, 15) {
		s.Log("Running kernel 5.10 or 5.15, skipping test. Nested Virt disabled due to CVE-2026-53359")
		return
	}

	if strings.Contains(s.TestName(), "baguette") {
		s.Log("Installing GCC")
		if err := cont.Command(ctx, "sudo", "apt-get", "update").Run(testexec.DumpLogOnError); err != nil {
			s.Fatal("Failed to run apt-update: ", err)
		}
		if err := cont.Command(ctx, "sudo", "apt-get", "-y", "install", "gcc").Run(testexec.DumpLogOnError); err != nil {
			s.Fatal("Failed to install GCC: ", err)
		}
	}

	if err := cont.Command(ctx, "ls", "/dev/kvm").Run(testexec.DumpLogOnError); err != nil {
		s.Fatal("Failed to find /dev/kvm in VM: ", err)
	}

	if err := cont.PushFile(ctx, s.DataPath("kvm_test.c-bypass-mask"), "kvm_test.c"); err != nil {
		s.Fatal("Failed to push test program to VM: ", err)
	}

	if err := cont.Command(ctx, "gcc", "kvm_test.c").Run(testexec.DumpLogOnError); err != nil {
		s.Fatal("Failed to build test program: ", err)
	}

	if err := testing.Poll(
		ctx,
		func(ctx context.Context) error {
			if output, err := cont.Command(ctx, "./a.out").CombinedOutput(testexec.DumpLogOnError); err != nil {
				return errors.Wrapf(err, "Test program output: %s", string(output))
			}
			return nil
		},
		&testing.PollOptions{Timeout: 10 * time.Second},
	); err != nil {
		s.Fatal("Failed to run test program: ", err)
	}
}
