func AppFirefoxEmoji(ctx context.Context, s *testing.State) {
	tconn := s.FixtValue().(crostini.FixtureData).Tconn
	cont := s.FixtValue().(crostini.FixtureData).Cont
	keyboard := s.FixtValue().(crostini.FixtureData).KB
	cr := s.FixtValue().(crostini.FixtureData).Chrome

	// Use a shortened context for test operations to reserve time for cleanup.
	cleanupCtx := ctx
	ctx, cancel := ctxutil.Shorten(ctx, 30*time.Second)
	defer cancel()

	// TODO(b/304160903): Disable CSD to work around IME bug.
	if err := crostiniapps.DisableFirefoxCSD(ctx, cont); err != nil {
		s.Fatal("Failed to disable client-side decorations: ", err)
	}

	// Open Terminal app.
	terminalApp, err := terminalapp.Launch(ctx, tconn)
	if err != nil {
		s.Fatal("Failed to open Terminal app: ", err)
	}
	defer terminalApp.Exit(keyboard)(cleanupCtx)

	// Since defers are executed in a stack, this needs to be the last defer so it doesn't close the window before dumping the tree.
	handler := faillog.DumpUITreeWithScreenshotHandler(cleanupCtx, tconn, "ui_tree")
	s.AttachErrorHandlers(handler, handler)

	const inputEmoji = "😂"
	ui := uiauto.New(tconn)
	uda := uidetection.NewDefault(tconn)

	if err := crostiniapps.LaunchFirefoxWithTestPage(ctx, tconn, uda, ui, cont, terminalApp, keyboard); err != nil {
		s.Fatal("Failed to create Firefox test page: ", err)
	}

	if err := uiauto.Combine("enter emoji in Firefox",
		imetestutil.OpenEmojiPickerAndInputEmoji(ctx, cr, keyboard, tconn, inputEmoji),
		func(ctx context.Context) error {
			return imetestutil.CheckInputViaClipboard(ctx, keyboard, tconn, inputEmoji)
		},
	)(ctx); err != nil {
		s.Fatal("Failed to enter emoji and verify input via clipboard: ", err)
	}

	if err := crostini.TakeAppScreenshot("firefox")(ctx); err != nil {
		s.Fatal("Failed to take app screenshot: ", err)
	}

	if err := crostiniapps.CloseFirefoxTestPage(ctx, uda, ui, cont, keyboard); err != nil {
		s.Fatal("Failed to close firefox: ", err)
	}
}
