func init() {
	testing.AddTest(&testing.Test{
		Func:         Chrony,
		LacrosStatus: testing.LacrosVariantUnneeded,
		Desc:         "Test PTP clock synchronization works",
		Contacts:     []string{"clumptini+oncall@google.com"},
		Attr:         []string{"group:mainline", "group:sw_gates_virt", "sw_gates_virt_enabled"},
		SoftwareDeps: []string{"chrome", "ptp_kvm", "vm_host"},
		BugComponent: "b:1122570",
		Params: []testing.Param{
			// Parameters generated by chrony_test.go. DO NOT EDIT.
			{
				Name:              "stable",
				ExtraSoftwareDeps: []string{"dlc"},
				ExtraHardwareDeps: crostini.CrostiniOptimalPerf,
				Fixture:           "crostiniBullseye",
				Timeout:           2 * time.Minute,
			},
		},
	})
}

func Chrony(ctx context.Context, s *testing.State) {
	cont := s.FixtValue().(crostini.FixtureData).Cont

	// We set a 4-second polling interval for chrony, so match that for retries.
	if err := action.Retry(15, func(context.Context) error {
		cmd := cont.VM.Command(ctx, "chronyc", "-c", "tracking")
		stdout, err := cmd.Output(testexec.DumpLogOnError)
		if err != nil {
			s.Logf("chronyc output: %q", stdout)
			s.Fatal("Failed to run chronyc: ", err)
		}

		output := strings.Split(string(stdout), ",")
		// The second field contains the reference name.
		if output[1] != "PHC0" {
			return errors.Errorf("unexpected reference %q", output[1])
		}

		return nil
	}, 4*time.Second)(ctx); err != nil {
		s.Fatal("Failed to check chrony: ", err)
	}
}
