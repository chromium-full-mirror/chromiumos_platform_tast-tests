func AppGeditSwitchIME(ctx context.Context, s *testing.State) {
	tconn := s.FixtValue().(crostini.FixtureData).Tconn
	cont := s.FixtValue().(crostini.FixtureData).Cont
	keyboard := s.FixtValue().(crostini.FixtureData).KB

	// Reserve time for clean-up tasks.
	cleanupCtx := ctx
	ctx, cancel := ctxutil.Shorten(ctx, 15*time.Second)
	defer cancel()

	// Open Terminal app.
	terminalApp, err := terminalapp.Launch(ctx, tconn)
	if err != nil {
		s.Fatal("Failed to open Terminal app: ", err)
	}
	defer terminalApp.Exit(keyboard)(cleanupCtx)

	handler := faillog.DumpUITreeWithScreenshotHandler(cleanupCtx, tconn, "ui_tree")
	s.AttachErrorHandlers(handler, handler)

	// Switch back to default IME.
	defer imetestutil.ResetToDefaultIME(cleanupCtx, tconn)

	if err := testSwitchIMEInGeditFile(ctx, terminalApp, keyboard, tconn, cont); err != nil {
		s.Fatal("Failed to use and switch IME in Gedit file: ", err)
	}
}

func testSwitchIMEInGeditFile(ctx context.Context, terminalApp *terminalapp.TerminalApp, keyboard *input.KeyboardEventWriter, tconn *chrome.TestConn, cont *vm.Container) error {
	const testFile = "test.txt"

	// Type in Japanese first, then type in English.
	japaneseIMEData := imetestutil.IMETestCases["japanese"]
	englishIMEData := imetestutil.IMETestCases["english"]

	ui := uiauto.New(tconn)
	uda := uidetection.NewDefault(tconn)
	appWindow := nodewith.NameStartingWith(testFile).Role(role.Window).First()

	testing.ContextLog(ctx, "Typing in Japanese")
	if err := uiauto.Combine("open Gedit via the terminal and type in Japanese",
		// Launch Gedit.
		terminalApp.RunCommand(keyboard, "gedit "+testFile),
		// Sometimes the first character gets lost if input is entered immediately.
		// Wait until the menu exists, indicating the window is launched.
		uda.WaitUntilExists(uidetection.Word("Open").WithinA11yNode(appWindow)),
		ui.LeftClick(appWindow),
		// Activate and type in Japanese.
		japaneseIMEData.InputMethod.InstallAndActivate(tconn),
		japaneseIMEData.InputMethod.WaitUntilActivated(tconn),
		japaneseIMEData.EnterTestStringActionPK(keyboard, ui),
		// Take screenshot.
		crostini.TakeAppScreenshot("Japanese in gedit"),
	)(ctx); err != nil {
		return err
	}

	testing.ContextLog(ctx, "Verifying Japanese input")
	if err := imetestutil.CheckInputViaClipboard(ctx, keyboard, tconn, japaneseIMEData.ExpectedText); err != nil {
		return errors.Wrap(err, "failed to verify initial Japanese input")
	}

	testing.ContextLog(ctx, "Typing in English")
	if err := uiauto.Combine("switch to English input method and continue typing",
		// Activate and type in English.
		englishIMEData.InputMethod.InstallAndActivate(tconn),
		englishIMEData.InputMethod.WaitUntilActivated(tconn),
		englishIMEData.EnterTestStringActionPK(keyboard, ui),
		// Take screenshot.
		crostini.TakeAppScreenshot("Japanese and English in gedit"),
		// Press ctrl+S to save the file.
		keyboard.AccelAction("ctrl+S"),
		// Press ctrl+W twice to exit window.
		keyboard.AccelAction("ctrl+W"),
		keyboard.AccelAction("ctrl+W"),
		// Check window close.
		ui.WaitUntilGone(appWindow),
	)(ctx); err != nil {
		return err
	}

	// Check that the contents of the test file includes both Japanese and English.
	expectedText := fmt.Sprintf("%s%s\n", japaneseIMEData.ExpectedText, englishIMEData.ExpectedText)
	if err := cont.CheckFileContent(ctx, testFile, expectedText); err != nil {
		return errors.Wrap(err, "failed to verify the content of the test file")
	}

	return nil
}
