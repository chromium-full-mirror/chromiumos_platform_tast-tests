const (
	// chromeCrashEarlyCleanupTimeout is the amount of time we reserve for
	// cleanup. We want to leave time to restart session manager and get it back
	// into a good state.
	chromeCrashEarlyCleanupTimeout = upstart.UIRestartTimeout

	// chromeCrashEarlyCrashFileTimeout is the amount of time we wait for the
	// crash files to appear. crash_reporter can take some time to collect info
	// from the chrome binary; the default 15 seconds had led to flakes.
	chromeCrashEarlyCrashFileTimeout = time.Minute

	chromeCrashBaseName = `chrome\.\d{8}\.\d{6}\.\d+\.\d+`
	chromeCrashMetaName = chromeCrashBaseName + `\.meta`
	chromeCrashDmpName  = chromeCrashBaseName + `\.dmp`

	// chromeCrashEarlyLooseModeFile is a file used by the "loose" subtest to tell
	// crash reporter that it should accept larger-than-normal core files during
	// this test. Must match crash-reporter's kSystemRunStateDirectory +
	// kRunningLooseChromeCrashEarlyTestFile.
	chromeCrashEarlyLooseModeFile = "/run/crash_reporter/running-loose-chrome-crash-early-test"
)

// chromeCrashEarlyParams contains the test parameters which are different between the various tests.
type chromeCrashEarlyParams struct {
	looseMode   bool
	browserType browser.Type
}

func init() {
	testing.AddTest(&testing.Test{
		Func:         ChromeCrashEarly,
		LacrosStatus: testing.LacrosVariantExists,
		Desc:         "Checks that if Chrome crashes before crashpad is initialized, the user collector collects the crash",
		Contacts:     []string{"chromeos-data-eng@google.com", "iby@chromium.org"},
		BugComponent: "b:1032705",
		Attr:         []string{"group:mainline", "group:hw_agnostic"},
		SoftwareDeps: []string{"chrome", "crashpad"},
		Params: []testing.Param{{
			Name: "strict",
			Val: chromeCrashEarlyParams{
				looseMode:   false,
				browserType: browser.TypeAsh,
			},
			Timeout:           upstart.UIRestartTimeout + chromeCrashEarlyCleanupTimeout + chromeCrashEarlyCrashFileTimeout + time.Minute,
			ExtraSoftwareDeps: []string{"chrome_internal"},
		}, {
			Name: "strict_lacros",
			Val: chromeCrashEarlyParams{
				looseMode:   false,
				browserType: browser.TypeLacros,
			},
			// Lacros test logs in so it needs more time.
			Timeout:           chrome.MinLoginTimeout + chromeCrashEarlyCleanupTimeout + chromeCrashEarlyCrashFileTimeout + time.Minute,
			ExtraSoftwareDeps: []string{"lacros"}, // There's no such thing as lacros_internal.
		}, {
			Name: "loose",
			Val: chromeCrashEarlyParams{
				looseMode:   true,
				browserType: browser.TypeAsh,
			},
			Timeout: upstart.UIRestartTimeout + chromeCrashEarlyCleanupTimeout + chromeCrashEarlyCrashFileTimeout + time.Minute,
		}, {
			Name: "loose_lacros",
			Val: chromeCrashEarlyParams{
				looseMode:   true,
				browserType: browser.TypeLacros,
			},
			// Lacros test logs in so it needs more time.
			Timeout:           chrome.MinLoginTimeout + chromeCrashEarlyCleanupTimeout + chromeCrashEarlyCrashFileTimeout + time.Minute,
			ExtraSoftwareDeps: []string{"lacros"},
		}}})
}

// filterMetaFiles takes a list of filenames and returns all the files that end
// in ".meta".
func filterMetaFiles(files []string) []string {
	var metaFiles []string
	for _, file := range files {
		if strings.HasSuffix(file, ".meta") {
			metaFiles = append(metaFiles, file)
		}
	}
	return metaFiles
}

func waitForEarlyCrashFiles(ctx context.Context, crashDirectories []string, expectedProductName string) error {
	outDir, ok := testing.ContextOutDir(ctx)
	if !ok {
		return errors.New("could not determine output directory to save problematic files")
	}
	regexes := []string{chromeCrashMetaName, chromeCrashDmpName}
	// Meta files generated by the early crash collection system will be collected
	// by UserCollector not ChromeCollector.
	const earlyCrashCollector = "upload_var_collector=user"
	// And should be marked as being handled by the early Chrome crash code.
	const earlyCrashMarker = "upload_var_early_chrome_crash=true"
	// And should be product name Chrome_ChromeOS or Chrome_Lacros, NOT the
	// ChromeOS product name normally used by UserCollector.
	expectedProductVar := "upload_var_prod=" + expectedProductName
	// And we should have a Chrome-like version number (four numbers separated
	// by dots) not a ChromeOS-like version number.
	expectedVersion := regexp.MustCompile(`upload_var_ver=\d+\.\d+\.\d+\.\d+\n`)
	// Since we're not logged in, the crashes will be written to
	// /home/chronos/crash/.
	if files, err := crash.WaitForCrashFiles(ctx, crashDirectories, regexes,
		crash.MetaString(earlyCrashCollector), crash.MetaString(earlyCrashMarker),
		crash.MetaString(expectedProductVar), crash.MetaRegExp(expectedVersion),
		crash.Timeout(chromeCrashEarlyCrashFileTimeout)); err != nil {
		// Failure investigation: Sometimes, it looks like util::IsReallyTestImage
		// is returning false and thus preventing mock consent from working. Copy
		// the various lsb-release files used by util::IsReallyTestImage to the
		// test results.
		if err := fsutil.CopyFile("/etc/lsb-release",
			filepath.Join(outDir, "etc-lsb-release")); err != nil {
			testing.ContextLog(ctx, "Failed to copy /etc/lsb-release for forensic analysis: ", err)
		}
		if err := fsutil.CopyFile("/var/lib/crash_reporter/lsb-release",
			filepath.Join(outDir, "var-lib-crash_reporter-lsb-release")); err != nil {
			testing.ContextLog(ctx, "Failed to copy /var/lib/crash_reporter/ for forensic analysis: ", err)
		}
		// Often, the meta file exists but doesn't have a match for one of the
		// crash.MetaString or crash.MetaRegExp requirements above. Copy the meta
		// files off so we can see which string is missing or corrupt.
		if regexesNotFoundError, ok := err.(crash.RegexesNotFound); ok {
			filesToSave := filterMetaFiles(regexesNotFoundError.Files)
			if err := crash.MoveFilesToOut(ctx, outDir, filesToSave...); err != nil {
				testing.ContextLog(ctx, "Failed to copy crash files for forensic analysis: ", err)
			}
		}

		return errors.Wrap(err, "couldn't find early crash files")
	} else if err := crash.RemoveAllFiles(ctx, files); err != nil {
		testing.ContextLog(ctx, "Couldn't clean up files: ", err)
	}
	return nil
}

// chromeCrashEarlyAsh implements the ash-specific heart of ChromeCrashEarly.
func chromeCrashEarlyAsh(ctx, cleanupCtx context.Context) error {
	// Stop and then start session manager. This ensures we are logged out which
	// improves the consistency of the test. (In particular, the crash files will
	// always be in crash.LocalCrashDir.)
	if err := upstart.RestartJob(ctx, "ui"); err != nil {
		return errors.Wrap(err, "failed to restart ui job")
	}

	if err := crash.SetUpCrashTest(ctx, crash.WithMockConsent()); err != nil {
		return errors.Wrap(err, "SetUpCrashTest failed")
	}
	defer crash.TearDownCrashTest(cleanupCtx)
	// Tell session manager to restart Chrome with a early crash. Don't use chrome.New;
	// the browser won't be up long enough for chrome.New to connect to it.
	sm, err := session.NewSessionManager(ctx)
	if err != nil {
		return errors.Wrap(err, "NewSessionManager failed")
	}

	testing.ContextLog(ctx, "Switching Chrome to insta-crash & waiting for crash files")
	extraArgs := chromecrash.GetExtraArgs(chromecrash.Crashpad, crash.MockConsent)
	extraArgs = append(extraArgs, "--pre-crashpad-crash-test")
	if _, err := sm.EnableChromeTesting(ctx, true, extraArgs, []string{}); err != nil {
		return errors.Wrap(err, "start-crash-looping-Chrome call failed")
	}

	const expectedProductName = "Chrome_ChromeOS"
	directories := []string{crash.LocalCrashDir}
	if err := waitForEarlyCrashFiles(ctx, directories, expectedProductName); err != nil {
		return errors.Wrap(err, "waiting for crash files failed")
	}

	return nil
}

// chromeCrashEarlyLacros implements the Lacros-specific heart of ChromeCrashEarly.
func chromeCrashEarlyLacros(ctx, cleanupCtx context.Context) error {
	// Start up Chrome, tell it to start Lacros, and have it pass
	// --pre-crashpad-crash-test to Lacros. We don't use the normal
	// browserfixt.SetUpWithNewChrome() or any other function that calls
	// lacros.Launch() because Lacros won't be up long enough for us to connect to
	// it.
	chromeOpts, err := lacrosfixt.NewConfig().Opts()
	if err != nil {
		return errors.Wrap(err, "could not get needed options for Lacros")
	}

	chromeOpts = append(chromeOpts,
		chrome.ExtraArgs(chromecrash.GetExtraArgs(chromecrash.Crashpad, crash.MockConsent)...),
		chrome.LacrosExtraArgs("--pre-crashpad-crash-test"))
	testing.ContextLog(ctx, "Starting up ash chrome")
	cr, err := chrome.New(ctx, chromeOpts...)
	if err != nil {
		return errors.Wrap(err, "could not start ash chrome")
	}
	defer cr.Close(cleanupCtx)

	if err := crash.SetUpCrashTest(ctx, crash.WithMockConsent()); err != nil {
		return errors.Wrap(err, "SetUpCrashTest failed")
	}
	defer crash.TearDownCrashTest(cleanupCtx)

	tconn, err := cr.TestAPIConn(ctx)
	if err != nil {
		return errors.Wrap(err, "failed to connect to ash-chrome test API")
	}
	testing.ContextLog(ctx, "Launching Lacros in insta-crash mode and waiting for crash files")
	if err := apps.Launch(ctx, tconn, apps.Lacros.ID); err != nil {
		return errors.Wrap(err, "failed to launch Lacros")
	}

	crashDirectories, err := crash.GetDaemonStoreCrashDirs(ctx)
	if err != nil {
		return errors.Wrap(err, "failed to get daemon store crash directories")
	}

	const expectedProductName = "Chrome_Lacros"
	if err := waitForEarlyCrashFiles(ctx, crashDirectories, expectedProductName); err != nil {
		return errors.Wrap(err, "waiting for crash files failed")
	}

	return nil
}

// ChromeCrashEarly tests that the user collector can capture Chrome crashes that
// happened before crashpad has had a chance to initialize.
func ChromeCrashEarly(ctx context.Context, s *testing.State) {
	// Give enough time for setting session manager back into a good state.
	cleanupCtx := ctx
	ctx, cancel := ctxutil.Shorten(ctx, chromeCrashEarlyCleanupTimeout)
	defer cancel()

	params := s.Param().(chromeCrashEarlyParams)
	if params.looseMode {
		// The Chrome CQ runs tast tests against Chrome builds which are built with
		// is_official_build = false. These builds generate much larger-than-normal
		// core files, exceeding crash reporter's normal limits on the size of the
		// core. Set the limit higher by touching
		// /run/crash_reporter/running-loose-chrome-crash-early-test so that we can
		// at least test other aspects of system.
		if err := ioutil.WriteFile(chromeCrashEarlyLooseModeFile, nil, 0644); err != nil {
			s.Fatal("Failed writing ChromeCrashEarly loose-mode file ", chromeCrashEarlyLooseModeFile, ": ", err)
		}
		defer func() {
			if err := os.Remove(chromeCrashEarlyLooseModeFile); err != nil && !os.IsNotExist(err) {
				s.Errorf("Failed to clean up %s: %s", chromeCrashEarlyLooseModeFile, err)
			}
		}()
	} else {
		if err := os.Remove(chromeCrashEarlyLooseModeFile); err != nil && !os.IsNotExist(err) {
			s.Fatalf("Failed to remove %s: %s", chromeCrashEarlyLooseModeFile, err)
		}
	}

	// Make sure that session manager is back into a good state before the next
	// test starts by restarting it to clear whatever extra crash arguments the
	// subfunctions added.
	defer func() {
		if err := upstart.RestartJob(cleanupCtx, "ui"); err != nil {
			s.Log("Couldn't cleanup-restart ui job: ", err)
		}
	}()

	if params.browserType == browser.TypeAsh {
		if err := chromeCrashEarlyAsh(ctx, cleanupCtx); err != nil {
			s.Error("Ash test failed: ", err)
		}
	} else {
		if err := chromeCrashEarlyLacros(ctx, cleanupCtx); err != nil {
			s.Error("Lacros test failed: ", err)
		}
	}
}
