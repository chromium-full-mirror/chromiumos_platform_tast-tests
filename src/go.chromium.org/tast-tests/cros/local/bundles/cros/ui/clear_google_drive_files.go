const (
	clearTimeout = 6 * time.Hour
	retryTimes   = 3

	// strategyMyDrive is the strategy to delete files before yesterday.
	strategyMyDrive = "mydrive"
	// strategyLarge is the strategy to quickly delete large files so that
	// it will no longer display the out of storage message.
	// But this method may delete files that are in use.
	strategyLarge = "large"
	// strategyCheck is the strategy to quickly check the storage usage
	// of all accounts to determine which accounts need to delete drive
	// files first.
	strategyCheck = "check"
)

func init() {
	testing.AddTest(&testing.Test{
		Func:         ClearGoogleDriveFiles,
		Desc:         "Clear all files in Google Drive before yesterday",
		Contacts:     []string{"chicheny@google.com"},
		BugComponent: "b:1045832",
		SoftwareDeps: []string{"chrome"},
		Timeout:      clearTimeout + 10*time.Minute,
		Vars:         []string{"ui.ClearGoogleDriveFiles.accountPool", "ui.ClearGoogleDriveFiles.skipSmallFiles"},
		Params: []testing.Param{
			{
				Name: "mydrive",
				Val:  strategyMyDrive,
			},
			{
				Name: "large",
				Val:  strategyLarge,
			},
			{
				Name: "check",
				Val:  strategyCheck,
			},
		},
	})
}

var (
	// storageUsageInfo collects per-account Drive usage summaries for logging.
	storageUsageInfo []string

	noMatchResultsText = nodewith.Name("No matching results").Role(role.StaticText)
	placeForAllText    = nodewith.Name("A place for all of your files").Role(role.StaticText)
)

// ClearGoogleDriveFiles is a tool to delete old Google documents from
// Google Drive which generated by our tests, not meant to be run in
// the lab or used in any performance capacity.
func ClearGoogleDriveFiles(ctx context.Context, s *testing.State) {
	accountPool := s.RequiredVar("ui.ClearGoogleDriveFiles.accountPool")
	cs, err := credconfig.ParseCreds(accountPool)
	if err != nil {
		s.Fatal("Failed to parse creds: ", err)
	}

	for _, c := range cs {
		clearAccountFiles(ctx, s, c.User, c.Pass)
	}
	if len(storageUsageInfo) > 0 {
		sort.Strings(storageUsageInfo)
		for _, info := range storageUsageInfo {
			testing.ContextLog(ctx, info)
		}
	}
}

func clearAccountFiles(ctx context.Context, s *testing.State, account, password string) {
	const (
		myDriveURL = "https://drive.google.com/drive/my-drive"
		largeURL   = "https://one.google.com/storage/management/drive/large"
	)
	// Start up Chrome.
	cr, err := chrome.New(ctx, chrome.GAIALogin(chrome.Creds{User: account, Pass: password}))
	if err != nil {
		s.Fatal("Failed to start Chrome: ", err)
	}

	tconn, err := cr.TestAPIConn(ctx)
	if err != nil {
		s.Fatal("Failed to connect to test API: ", err)
	}
	ui := uiauto.New(tconn)

	var url string
	var strategyAction func(context.Context) error
	strategy := s.Param().(string)
	switch strategy {
	case strategyMyDrive:
		url = myDriveURL
		strategyAction = func(ctx context.Context) error {
			return clearFromMyDrive(ctx, tconn, ui)
		}

	case strategyLarge:
		skipSmallFiles := false
		skipSmallFilesStr, ok := s.Var("ui.ClearGoogleDriveFiles.skipSmallFiles")
		if ok {
			var err error
			skipSmallFiles, err = strconv.ParseBool(skipSmallFilesStr)
			if err != nil {
				s.Fatal("Failed to parse ui.ClearGoogleDriveFiles.skipSmallFiles: ", err)
			}
		}

		url = largeURL
		strategyAction = func(ctx context.Context) error {
			return clearLargeDriveFiles(ctx, tconn, ui, skipSmallFiles)
		}
	case strategyCheck:
		url = myDriveURL
		strategyAction = func(ctx context.Context) error {
			return extractStorageUsage(ctx, ui, account)
		}
	}

	cleanupCtx := ctx
	ctx, cancel := ctxutil.Shorten(ctx, 10*time.Second)
	defer cancel()

	conn, err := cr.NewConn(ctx, url)
	if err != nil {
		s.Fatal("Failed open Google Drive: ", err)
	}
	defer conn.Close()
	defer conn.CloseTarget(cleanupCtx)
	defer faillog.DumpUITreeWithScreenshotOnError(cleanupCtx, s.OutDir(), s.HasError, cr, "ui_dump")

	// Ensure the browser window is maximized.
	if err := policyutil.MaximizeActiveWindow(ctx, tconn); err != nil {
		s.Fatal("Failed to maximize the browser window: ", err)
	}

	if err := webutil.WaitForQuiescence(ctx, conn, time.Minute); err != nil {
		s.Fatal("Failed to wait for the page loaded: ", err)
	}

	if err := strategyAction(ctx); err != nil {
		s.Fatal("Failed to do stratefy action: ", err)
	}
}

func clearFromMyDrive(ctx context.Context, tconn *chrome.TestConn, ui *uiauto.Context) error {
	// Start up keyboard.
	kb, err := input.Keyboard(ctx)
	if err != nil {
		return errors.Wrap(err, "failed to open keyboard")
	}
	defer kb.Close(ctx)

	if err := selectYesterdayFilter(ctx, ui); err != nil {
		return errors.Wrap(err, "failed to select filter")
	}

	attempts := 0
	endTime := time.Now().Add(clearTimeout)
	for {
		if err := moveToTrash(ctx, ui, kb); err != nil {
			if ui.WaitUntilAnyExists(noMatchResultsText, placeForAllText)(ctx) == nil {
				testing.ContextLog(ctx, "Matching files have been deleted")
				if err := emptyTrash(ctx, ui); err != nil {
					return errors.Wrap(err, "failed to empty trash")
				}
				break
			} else {
				if attempts == retryTimes {
					return errors.Wrap(err, "failed to move to trash")
				}
				testing.ContextLog(ctx, "Failed to move to trash: ", err)

				attempts++
				testing.ContextLogf(ctx, "Reloading the page and retrying (attempt #%d)", attempts)
				if reloadErr := browser.ReloadActiveTab(ctx, tconn); reloadErr != nil {
					return errors.Wrap(reloadErr, "failed to reload active tab")
				}
			}
		} else {
			// Reset attempts after a successful deletion to avoid unnecessary
			// retries on next failure.
			attempts = 0
		}

		if time.Now().After(endTime) {
			testing.ContextLogf(ctx, "It has been deleting files for %q and has not yet finished", clearTimeout)
			break
		}
	}

	return nil
}

func selectYesterdayFilter(ctx context.Context, ui *uiauto.Context) error {
	modifiedButton := nodewith.Name("Modified").Role(role.Button)
	customDateRangeCheckBox := nodewith.Name("Custom date range").Role(role.MenuItemCheckBox)
	beforeButton := nodewith.Name("Before with no date selected").Role(role.Button)
	calendarRegion := nodewith.Name("Calendar").Role(role.Region)
	yesterday := time.Now().AddDate(0, 0, -1)
	yesterdayStr := fmt.Sprintf("%d-%.2d-%.2d", yesterday.Year(), yesterday.Month(), yesterday.Day())
	yesterdayButtonStr := fmt.Sprintf("%s %.2d", yesterday.Month().String(), yesterday.Day())
	yesterdayButton := nodewith.Name(yesterdayButtonStr).Role(role.Button).Ancestor(calendarRegion).First()
	yesterdayText := nodewith.Name(yesterdayStr).Role(role.StaticText)
	applyButton := nodewith.Name("Apply").Role(role.Button)
	return uiauto.Retry(retryTimes, uiauto.NamedCombine("select yesterday filter",
		ui.DoDefault(modifiedButton),
		ui.DoDefault(customDateRangeCheckBox),
		ui.DoDefault(beforeButton),
		ui.WaitUntilExists(calendarRegion),
		func(ctx context.Context) error {
			previousMonth := nodewith.Name("previous month").Role(role.Button)
			if time.Now().Day() == 1 {
				return uiauto.NamedAction("select previous month", ui.DoDefault(previousMonth))(ctx)
			}
			return nil
		},
		ui.DoDefaultUntil(yesterdayButton, ui.WithTimeout(5*time.Second).WaitUntilExists(yesterdayText)),
		ui.DoDefault(applyButton),
		ui.WaitUntilGone(applyButton),
	))(ctx)
}

func moveToTrash(ctx context.Context, ui *uiauto.Context, kb *input.KeyboardEventWriter) error {
	dismissDialogs := func() action.Action {
		buttons := []*nodewith.Finder{
			nodewith.Name("Hide Details").Role(role.Button),
			nodewith.Name("Close").Role(role.Button).Ancestor(nodewith.Role(role.Dialog)),
			nodewith.Name("Dismiss").Role(role.Button).First(),
		}

		actions := make([]uiauto.Action, len(buttons))
		for i, btn := range buttons {
			actions[i] = uiauto.IfSuccessThen(ui.Exists(btn), ui.DoDefault(btn))
		}

		return uiauto.Combine("dismiss dialogs", actions...)
	}

	row1 := nodewith.Role(role.Row).First()
	signedOutText := nodewith.Name("You are not signed in").Role(role.StaticText)
	reloadButton := nodewith.Name("Reload").Role(role.Button).First()
	moveToTrashButton := nodewith.NameRegex(regexp.MustCompile(`(Move to trash|Remove)`)).Role(role.Button).First()
	return uiauto.NamedCombine("move to trash",
		dismissDialogs(),
		func(ctx context.Context) error {
			if ui.Exists(signedOutText)(ctx) == nil {
				return errors.New("the account has been signed out")
			}
			if ui.Exists(placeForAllText)(ctx) == nil || ui.Exists(noMatchResultsText)(ctx) == nil {
				return errors.New("matching files have been deleted")
			}
			return nil
		},
		uiauto.IfFailThen(
			ui.WaitUntilExists(row1),
			ui.DoDefault(reloadButton),
		),
		ui.WithTimeout(time.Minute).DoDefaultUntil(row1, ui.WithTimeout(10*time.Second).WaitUntilExists(moveToTrashButton)),
		kb.AccelPressAction("Shift+Down"),
		uiauto.Sleep(time.Second),
		kb.AccelReleaseAction("Shift+Down"),
		ui.WithTimeout(time.Minute).DoDefaultUntil(moveToTrashButton,
			ui.WaitUntilGone(moveToTrashButton)),
	)(ctx)
}

func emptyTrash(ctx context.Context, ui *uiauto.Context) error {
	trashText := nodewith.Name("Trash").Role(role.StaticText)
	nothingInTrashText := nodewith.Name("Nothing in Trash").Role(role.StaticText)
	emptyTrashButton := nodewith.Name("Empty trash").Role(role.Button)
	deleteButton := nodewith.Name("Delete forever").Role(role.Button)
	emptyText := nodewith.Name("Trash is empty").Role(role.Heading)
	deleteAllFiles := uiauto.NamedCombine("delete all files",
		ui.DoDefault(emptyTrashButton),
		ui.DoDefault(deleteButton),
		func(ctx context.Context) error {
			if err := ui.WithTimeout(time.Minute).WaitUntilExists(emptyText)(ctx); err != nil {
				testing.ContextLog(ctx, "There are too many files in trash, and it will take a long time to delete all files")
			} else {
				testing.ContextLog(ctx, "Trash is empty")
			}
			return nil
		})
	return uiauto.NamedCombine("empty trash",
		ui.DoDefault(trashText),
		ui.WaitUntilAnyExists(nothingInTrashText, emptyTrashButton, emptyText),
		uiauto.IfSuccessThen(
			ui.Exists(emptyTrashButton),
			deleteAllFiles,
		),
	)(ctx)
}

func clearLargeDriveFiles(ctx context.Context, tconn *chrome.TestConn, ui *uiauto.Context, skipSmallFiles bool) error {
	getShowingNum := func(ctx context.Context) (int, error) {
		showingRegex := regexp.MustCompile(`Showing \((\d+)\)`)
		showingNumberText := nodewith.NameRegex(showingRegex).Role(role.ColumnHeader)
		node, err := ui.Info(ctx, showingNumberText)
		if err != nil {
			return 0, errors.Wrap(err, "failed to get showing info")
		}
		match := showingRegex.FindStringSubmatch(node.Name)
		if len(match) > 1 {
			number, err := strconv.Atoi(match[1])
			if err != nil {
				return 0, errors.Wrap(err, "failed to get number")
			}
			return number, nil
		}
		return 0, nil
	}

	showMoreItems := func(ctx context.Context) error {
		showMoreButton := nodewith.Name("Show more items").Role(role.Button)
		showing96Button := nodewith.NameContaining("Showing (96)").Role(role.ColumnHeader)
		// Google Drive can delete up to 100 items at a time.
		// Click show more twice to select 96 items to delete at a time.
		if err := ui.DoDefaultUntil(showMoreButton,
			ui.WithTimeout(3*time.Second).WaitUntilExists(showing96Button))(ctx); err != nil {
			showingNumber, err := getShowingNum(ctx)
			if err != nil {
				return errors.Wrap(err, "failed to get showing number")
			}
			testing.ContextLog(ctx, "showing number is ", showingNumber)
			return nil
		}
		return nil
	}

	shouldStopDeletion := false

	markStopIfSmallFilesExist := func(ctx context.Context) error {
		if skipSmallFiles {
			kbText := nodewith.NameContaining("KB").Role(role.StaticText).First()
			if err := ui.Exists(kbText)(ctx); err == nil {
				shouldStopDeletion = true
			}
		}
		return nil
	}

	noLargeFiles := nodewith.Name("No large drive files to delete").Role(role.StaticText)
	selectAllItemsCheckBox := nodewith.Name("Select all items").Role(role.CheckBox)
	notNowButton := nodewith.Name("Not now").Role(role.Button)
	deleteButton := nodewith.Name("Delete").Role(role.Button)
	understandText := nodewith.Name("I understand that deleted items can't be recovered.").Role(role.StaticText)
	permanentlyDeleteButton := nodewith.Name("Permanently delete").Role(role.Button)
	message := nodewith.NameContaining("It'll take a moment").Role(role.StaticText)

	deleteLargeDriveFiles := uiauto.NamedCombine("delete large drive files",
		uiauto.IfSuccessThen(ui.Exists(notNowButton), ui.DoDefault(notNowButton)),
		showMoreItems,
		ui.DoDefaultUntil(selectAllItemsCheckBox,
			ui.WithTimeout(3*time.Second).WaitUntilExists(selectAllItemsCheckBox.Focused())),
		ui.DoDefault(deleteButton),
		ui.DoDefault(understandText),
		ui.DoDefault(permanentlyDeleteButton),
		ui.WithTimeout(time.Minute).WaitUntilExists(message),
		markStopIfSmallFilesExist,
		ui.WaitUntilGone(message),
	)

	attempts := 0
	after := time.Now().Add(clearTimeout)
	for {
		if err := uiauto.Combine("check for large files",
			ui.WaitUntilAnyExists(noLargeFiles, selectAllItemsCheckBox),
			ui.Exists(noLargeFiles),
		)(ctx); err == nil {
			testing.ContextLog(ctx, "There is no large files to delete")
			break
		}
		if err := deleteLargeDriveFiles(ctx); err != nil {
			if attempts == retryTimes {
				return errors.Wrap(err, "failed to delete large drive files")
			}
			testing.ContextLog(ctx, "Failed to delete large drive files: ", err)

			attempts++
			testing.ContextLogf(ctx, "Reloading the page and retrying (attempt #%d)", attempts)
			if reloadErr := browser.ReloadActiveTab(ctx, tconn); reloadErr != nil {
				return errors.Wrap(reloadErr, "failed to reload active tab")
			}
		} else {
			// Reset attempts after a successful deletion to avoid unnecessary
			// retries on next failure.
			attempts = 0
		}

		if skipSmallFiles && shouldStopDeletion {
			testing.ContextLog(ctx, "Large files are deleted; small files (size < 1MB) are skipped")
			break
		}

		if time.Now().After(after) {
			testing.ContextLogf(ctx, "It has been deleting files for %q and has not yet finished", clearTimeout)
			break
		}
	}

	return nil
}

func extractStorageUsage(ctx context.Context, ui *uiauto.Context, account string) error {
	const storageSummaryText = "Storage Summary: "
	storageText := nodewith.NameContaining(storageSummaryText)
	storageNodeInfo, err := ui.Info(ctx, storageText)
	if err != nil {
		return errors.Wrap(err, "failed to get storage info")
	}
	storageSummary := strings.TrimPrefix(storageNodeInfo.Name, storageSummaryText)
	storageUsageInfo = append(storageUsageInfo, account+": "+storageSummary)

	return nil
}
