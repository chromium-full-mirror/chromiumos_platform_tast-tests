const clearTimeout = 6 * time.Hour

func init() {
	testing.AddTest(&testing.Test{
		Func:         ClearGoogleDriveFiles,
		LacrosStatus: testing.LacrosVariantUnneeded,
		Desc:         "Clear all files in Google Drive before yesterday",
		Contacts:     []string{"chicheny@google.com"},
		BugComponent: "b:1045832",
		SoftwareDeps: []string{"chrome"},
		Timeout:      clearTimeout + 10*time.Minute,
		Vars:         []string{"ui.ClearGoogleDriveFiles.accountPool"},
	})
}

// ClearGoogleDriveFiles is a tool to delete old Google documents from
// Google Drive which generated by our tests, not meant to be run in
// the lab or used in any performance capacity.
func ClearGoogleDriveFiles(ctx context.Context, s *testing.State) {
	accountPool := s.RequiredVar("ui.ClearGoogleDriveFiles.accountPool")
	cs, err := credconfig.ParseCreds(accountPool)
	if err != nil {
		s.Fatal("Failed to parse creds: ", err)
	}

	for _, c := range cs {
		clearAccountFiles(ctx, s, c.User, c.Pass)
	}
}

func clearAccountFiles(ctx context.Context, s *testing.State, account, password string) {
	// Start up Chrome.
	cr, err := chrome.New(ctx, chrome.GAIALogin(chrome.Creds{User: account, Pass: password}))
	if err != nil {
		s.Fatal("Failed to start Chrome: ", err)
	}

	tconn, err := cr.TestAPIConn(ctx)
	if err != nil {
		s.Fatal("Failed to connect to test API: ", err)
	}

	cleanupCtx := ctx
	ctx, cancel := ctxutil.Shorten(ctx, 10*time.Second)
	defer cancel()

	conn, err := cr.NewConn(ctx, "https://drive.google.com/drive/my-drive")
	if err != nil {
		s.Fatal("Failed open Google Drive: ", err)
	}
	defer conn.Close()
	defer conn.CloseTarget(cleanupCtx)
	defer faillog.DumpUITreeWithScreenshotOnError(cleanupCtx, s.OutDir(), s.HasError, cr, "ui_dump")

	// Start up keyboard.
	kb, err := input.Keyboard(ctx)
	if err != nil {
		s.Fatal("Failed to open keyboard: ", err)
	}
	defer kb.Close(ctx)

	if err := selectYesterdayFilter(ctx, tconn); err != nil {
		s.Fatal("Failed to select filter: ", err)
	}

	ui := uiauto.New(tconn)
	noMatchResultsText := nodewith.Name("No matching results").Role(role.StaticText)
	if ui.WaitUntilExists(noMatchResultsText)(ctx) == nil {
		s.Log("Matching files have been deleted")
		if err := emptyTrash(ctx, tconn); err != nil {
			s.Fatal("Failed to empty trash: ", err)
		}
		return
	}

	row1 := nodewith.Role(role.Row).First()
	signedOutText := nodewith.Name("You are not signed in").Role(role.StaticText)
	hideDetailsButton := nodewith.Name("Hide Details").Role(role.Button)
	reloadButton := nodewith.Name("Reload").Role(role.Button).First()
	closeDialogButton := nodewith.Name("Close").Role(role.Button).Ancestor(nodewith.Role(role.Dialog))
	moveToTrashButton := nodewith.NameRegex(regexp.MustCompile(`(Move to trash|Remove)`)).Role(role.Button).First()

	moveToTrash := uiauto.NamedCombine("move to trash",
		func(ctx context.Context) error {
			if ui.Exists(signedOutText)(ctx) == nil {
				return errors.New("the account has been signed out")
			}
			if ui.Exists(noMatchResultsText)(ctx) == nil {
				return errors.New("matching files have been deleted")
			}
			return nil
		},
		uiauto.IfSuccessThen(
			ui.Exists(hideDetailsButton),
			ui.DoDefault(hideDetailsButton),
		),
		uiauto.IfSuccessThen(
			ui.Exists(closeDialogButton),
			ui.DoDefault(closeDialogButton),
		),
		uiauto.IfFailThen(
			ui.WaitUntilExists(row1),
			ui.DoDefault(reloadButton),
		),
		ui.WithTimeout(time.Minute).DoDefaultUntil(row1, ui.WithTimeout(10*time.Second).WaitUntilExists(moveToTrashButton)),
		kb.AccelPressAction("Shift+Down"),
		uiauto.Sleep(time.Second),
		kb.AccelReleaseAction("Shift+Down"),
		ui.WithTimeout(time.Minute).DoDefaultUntil(moveToTrashButton, ui.WaitUntilGone(moveToTrashButton)),
	)

	after := time.Now().Add(clearTimeout)
	for {
		if err := uiauto.Retry(3, moveToTrash)(ctx); err != nil {
			if ui.WaitUntilExists(noMatchResultsText)(ctx) == nil {
				s.Log("Matching files have been deleted")
				if err := emptyTrash(ctx, tconn); err != nil {
					s.Fatal("Failed to empty trash: ", err)
				}
				break
			} else {
				s.Fatal("Failed to move to trash: ", err)
			}
		}

		if time.Now().After(after) {
			s.Logf("It has been deleting files for %q and has not yet finished", clearTimeout)
			break
		}
	}
}

func selectYesterdayFilter(ctx context.Context, tconn *chrome.TestConn) error {
	ui := uiauto.New(tconn)
	modifiedButton := nodewith.Name("Modified").Role(role.Button)
	customDateRangeCheckBox := nodewith.Name("Custom date range").Role(role.MenuItemCheckBox)
	beforeButton := nodewith.Name("Before with no date selected").Role(role.Button)
	calendarRegion := nodewith.Name("Calendar").Role(role.Region)
	yesterday := time.Now().AddDate(0, 0, -1)
	yesterdayStr := fmt.Sprintf("%d-%.2d-%.2d", yesterday.Year(), yesterday.Month(), yesterday.Day())
	yesterdayButtonStr := fmt.Sprintf("%s %.2d", yesterday.Month().String(), yesterday.Day())
	yesterdayButton := nodewith.Name(yesterdayButtonStr).Role(role.Button).Ancestor(calendarRegion).First()
	yesterdayText := nodewith.Name(yesterdayStr).Role(role.StaticText)
	applyButton := nodewith.Name("Apply").Role(role.Button)

	return uiauto.Retry(3, uiauto.NamedCombine("select yesterday filter",
		ui.DoDefault(modifiedButton),
		ui.DoDefault(customDateRangeCheckBox),
		ui.DoDefault(beforeButton),
		ui.WaitUntilExists(calendarRegion),
		func(ctx context.Context) error {
			previousMonth := nodewith.Name("previous month").Role(role.Button)
			if time.Now().Day() == 1 {
				return uiauto.NamedAction("select previous month", ui.DoDefault(previousMonth))(ctx)
			}
			return nil
		},
		ui.DoDefaultUntil(yesterdayButton, ui.WithTimeout(5*time.Second).WaitUntilExists(yesterdayText)),
		ui.DoDefault(applyButton),
	))(ctx)
}

func emptyTrash(ctx context.Context, tconn *chrome.TestConn) error {
	ui := uiauto.New(tconn)
	trashText := nodewith.Name("Trash").Role(role.StaticText)
	nothingInTrashText := nodewith.Name("Nothing in Trash").Role(role.StaticText)
	emptyTrashButton := nodewith.Name("Empty trash").Role(role.Button)
	deleteButton := nodewith.Name("Delete forever").Role(role.Button)
	emptyText := nodewith.Name("Trash is empty").Role(role.Heading)
	deleteAllFiles := uiauto.NamedCombine("delete all files",
		ui.DoDefault(emptyTrashButton),
		ui.DoDefault(deleteButton),
		func(ctx context.Context) error {
			if err := ui.WithTimeout(time.Minute).WaitUntilExists(emptyText)(ctx); err != nil {
				testing.ContextLog(ctx, "There are too many files in trash, and it will take a long time to delete all files")
			} else {
				testing.ContextLog(ctx, "Trash is empty")
			}
			return nil
		})

	return uiauto.NamedCombine("empty trash",
		ui.DoDefault(trashText),
		ui.WaitUntilAnyExists(nothingInTrashText, emptyTrashButton, emptyText),
		uiauto.IfSuccessThen(
			ui.Exists(emptyTrashButton),
			deleteAllFiles,
		),
	)(ctx)
}
