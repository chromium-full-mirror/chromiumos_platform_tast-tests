func HotspotUpdateConfigurationWhenHotspotOn(ctx context.Context, s *testing.State) {
	cleanupCtx := ctx
	ctx, cancel := ctxutil.Shorten(ctx, 10*time.Second)
	defer cancel()

	cr, err := chrome.New(ctx, chrome.EnableFeatures("Hotspot"))
	if err != nil {
		s.Fatal("Failed to create a new instance of Chrome: ", err)
	}
	defer cr.Close(cleanupCtx)

	helper := s.FixtValue().(*cellular.FixtData).Helper
	if _, err := helper.Connect(ctx); err != nil {
		s.Fatal("Failed to connect to cellular service: ", err)
	}

	tconn, err := cr.TestAPIConn(ctx)
	if err != nil {
		s.Fatal("Failed to create Test API connection: ", err)
	}

	hs, err := ossettings.LaunchAtHotspotSubpage(ctx, tconn, cr)
	if err != nil {
		s.Fatal("Failed to open hotspot subpage: ", err)
	}
	defer faillog.DumpUITreeWithScreenshotOnError(cleanupCtx, s.OutDir(), s.HasError, cr, "ui_tree")

	tc, err := helper.Manager.GetTetheringConfig(ctx)
	if err != nil {
		s.Fatal("Failed to get tethering config: ", err)
	}

	if err := hs.ToggleHotspot(ctx, tconn, cr, true); err != nil {
		s.Fatal("Failed to toggle on hotspot")
	}

	ui := uiauto.New(tconn)
	if err := ui.WaitUntilExists(nodewith.Name(tc.Ssid).Role(role.StaticText))(ctx); err != nil {
		s.Fatalf("Failed to find matched hotspot Ssid: %s in subpage: %v", tc.Ssid, err)
	}

	const newSsid = "new_ssid"
	if err := hs.RenameHotspotSsid(ctx, tc.Ssid, newSsid)(ctx); err != nil {
		s.Fatal("Failed to rename hotspot ssid: ", err)
	}

	if err := uiauto.Combine("Check hotspot status for restarting",
		ui.WaitUntilExists(ossettings.HotspotTurningOnSublabel),
		ui.WaitUntilExists(ossettings.HotspotOnSublabel),
	)(ctx); err != nil {
		s.Fatal("Failed to restart hotspot: ", err)
	}

	if err := ui.WaitUntilExists(nodewith.Name(newSsid).Role(role.StaticText))(ctx); err != nil {
		s.Fatalf("Failed to find matched hotspot Ssid: %s after renaming in subpage: %v", tc.Ssid, err)
	}
}
