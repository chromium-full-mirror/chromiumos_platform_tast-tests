func HotspotAbortEnable(ctx context.Context, s *testing.State) {
	cleanupCtx := ctx
	ctx, cancel := ctxutil.Shorten(ctx, 10*time.Second)
	defer cancel()

	cr, err := chrome.New(ctx, chrome.EnableFeatures("Hotspot"))
	if err != nil {
		s.Fatal("Failed to create a new instance of Chrome: ", err)
	}

	helper := s.FixtValue().(*cellular.FixtData).Helper
	if _, err := helper.Connect(ctx); err != nil {
		s.Fatal("Failed to connect cellular service: ", err)
	}

	tconn, err := cr.TestAPIConn(ctx)
	if err != nil {
		s.Fatal("Failed to create Test API connection: ", err)
	}

	networkPage, err := ossettings.LaunchAtPage(ctx, tconn, ossettings.Network)
	if err != nil {
		s.Fatal("Failed to launch Network page: ", err)
	}
	defer faillog.DumpUITreeWithScreenshotOnError(cleanupCtx, s.OutDir(), s.HasError, cr, "ui_tree")

	const toggleName = "Hotspot enable"
	if enabled, err := networkPage.IsToggleOptionEnabled(ctx, cr, toggleName); err != nil {
		s.Fatal("Hotspot toggle should not be enabled: ", err)
	} else if enabled {
		s.Fatal("Hotspot toggle should not be enabled")
	}

	ui := uiauto.New(tconn)
	if err := uiauto.Combine("Toggle on hotspot",
		ui.LeftClick(ossettings.HotspotToggle),
		ui.WaitUntilExists(ossettings.HotspotTurningOnSublabel),
	)(ctx); err != nil {
		s.Fatal("Failed to toggle on hotspot and see turning on sublabel: ", err)
	}

	// GoBigSleepLint: simulate a short delay before user toggle off hotspot.
	testing.Sleep(ctx, 500*time.Millisecond)

	if err := uiauto.Combine("Abort enable hotspot",
		ui.LeftClick(ossettings.HotspotToggle),
		ui.WaitUntilExists(ossettings.HotspotOffSublabel),
	)(ctx); err != nil {
		s.Fatal("Failed to abort enable hotspot: ", err)
	}

	// Make sure hotspot can still be turned on and off successfully.
	if err := networkPage.ToggleHotspot(ctx, tconn, cr, true); err != nil {
		s.Fatal("Failed to start hotspot: ", err)
	}
	if err := networkPage.ToggleHotspot(ctx, tconn, cr, false); err != nil {
		s.Fatal("Failed to end hotspot: ", err)
	}
}
