func HotspotDisabledWhenNoUpstreamNetwork(ctx context.Context, s *testing.State) {
	cleanupCtx := ctx
	ctx, cancel := ctxutil.Shorten(ctx, 10*time.Second)
	defer cancel()

	cr, err := chrome.New(ctx, chrome.EnableFeatures("Hotspot", "TetheringExperimentalFunctionality"))
	if err != nil {
		s.Fatal("Failed to create a new instance of Chrome: ", err)
	}
	defer cr.Close(cleanupCtx)

	tconn, err := cr.TestAPIConn(ctx)
	if err != nil {
		s.Fatal("Failed to create Test API connection: ", err)
	}

	helper := s.FixtValue().(*cellular.FixtData).Helper
	if err := helper.IsConnected(ctx); err == nil {
		if _, err := helper.Disconnect(ctx); err != nil {
			s.Fatal("Failed to disconnect cellular service: ", err)
		}
	}

	if _, err := ossettings.LaunchAtPage(ctx, tconn, ossettings.Internet); err != nil {
		s.Fatal("Failed to launch Network page: ", err)
	}
	defer faillog.DumpUITreeWithScreenshotOnError(cleanupCtx, s.OutDir(), s.HasError, cr, "ui_tree")

	ui := uiauto.New(tconn)

	if err := uiauto.Combine("Check hotspot toggle disabled and learn more link",
		ui.CheckRestriction(ossettings.HotspotToggle, restriction.Disabled),
		ui.WaitUntilExists(nodewith.Name("Connect to mobile data to use hotspot. Learn more").Role(role.Link)),
	)(ctx); err != nil {
		s.Fatal("Hotspot toggle is not disabled or learn more link is not shown: ", err)
	}
}
