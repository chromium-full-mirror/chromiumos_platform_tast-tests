package wifi

import (
	"context"
	"io/ioutil"
	"os"
	"path/filepath"
	"strings"

	"go.chromium.org/tast-tests/cros/common/testexec"
	"go.chromium.org/tast-tests/cros/local/crash"
	"go.chromium.org/tast/core/errors"
)

const (
	firmwareDumpPattern       = `devcoredump_iwlwifi.*`
	kernalIwlwifiCrashPattern = `kernel_iwlwifi_error.*`

	// IwlwifiDir defines the Intel driver debugfs directory.
	IwlwifiDir = "/sys/kernel/debug/iwlwifi"
	// IwlwififwDbgCollect defines the debugfs API for triggering firmware dump.
	IwlwififwDbgCollect = "/iwlmvm/fw_dbg_collect"
)

// SaveDebugData saves the debug data generated by |command| to test's output
// directory named as "<outDir>/<outputFile>"".
func SaveDebugData(ctx context.Context, outDir, outputFile, command string) error {
	output, err := testexec.CommandContext(ctx, "bash", "-c", command).Output(testexec.DumpLogOnError)
	if err != nil {
		return errors.Wrapf(err, "failed to execute command %s", command)
	}
	err = ioutil.WriteFile(filepath.Join(outDir, outputFile), output, 0644)
	if err != nil {
		return errors.Wrapf(err, "failed to save debug data to %s", outputFile)
	}
	return nil
}

// SaveCrashData moves WiFi related crash files under /var/spool/crash to the
// test output directory.
func SaveCrashData(ctx context.Context, outDir string) error {
	crashDirs := []string{crash.SystemCrashDir}
	var requiredCrashMeta []string
	optionalCrashMeta := []string{
		firmwareDumpPattern + crash.MetadataExt,
		kernalIwlwifiCrashPattern + crash.MetadataExt,
	}
	// We don't have any expectations on a particular type of crash file and the
	// goal is to collect at best effort. Therefore, all crash file formats are
	// in the optional list so that they won't fail the test when missing.
	metaFilesMap, err := crash.WaitForCrashFiles(ctx, crashDirs, requiredCrashMeta, crash.OptionalRegexes(optionalCrashMeta))
	if err != nil {
		return errors.Wrap(err, "failed to find meta crash files")
	}
	// Find all payload and log files associated with the meta file, and save
	// them together with the meta file for crash data exportation.
	var outputFiles []string
	for _, metaFiles := range metaFilesMap {
		for _, metaFile := range metaFiles {
			outputFiles = append(outputFiles, metaFile)
			contents, err := os.ReadFile(metaFile)
			if err != nil {
				return errors.Wrapf(err, "failed to read meta file %s", metaFile)
			}
			dir := filepath.Dir(metaFile)
			// The payload and log files associated with the meta file have been
			// verified by |crash.WaitForCrashFiles|. Here, assume they exist
			// without further error handling.
			for _, line := range strings.Split(string(contents), "\n") {
				if !strings.HasPrefix(line, "payload=") && !strings.HasPrefix(line, "upload_file_") {
					continue
				}
				refFile := strings.Split(line, "=")[1]
				outputFiles = append(outputFiles, filepath.Join(dir, refFile))
			}
		}
	}

	if err := crash.MoveFilesToOut(ctx, outDir, outputFiles...); err != nil {
		return errors.Wrap(err, "failed to save unexpected crashes")
	}
	return nil
}

// TriggerFirmwareDump triggers firmware dump at best effort by finding and
// calling the debugfs API for firmware dump collection. If not found, this func
// assumes the operation is not supported by the driver and doesn't log error.
func TriggerFirmwareDump(ctx context.Context) error {
	entries, err := os.ReadDir(IwlwifiDir)
	if err != nil {
		return errors.Wrapf(err, "debugfs operations may not be supported -- failed to find/open directory %s", IwlwifiDir)
	}
	success := false
	for _, entry := range entries {
		fwDbgCollect := filepath.Join(IwlwifiDir, entry.Name(), IwlwififwDbgCollect)
		if _, err := os.Stat(fwDbgCollect); err != nil {
			continue
		}
		if err := os.WriteFile(fwDbgCollect, []byte("1"), 0); err != nil {
			return errors.Wrapf(err, "debugfs operation found for %s, but failed to trigger", fwDbgCollect)
		}
		success = true
		break
	}
	if !success {
		return errors.New("debugfs operations may not be supported for " + IwlwififwDbgCollect)
	}
	return nil
}
