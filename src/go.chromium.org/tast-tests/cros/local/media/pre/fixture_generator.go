package pre

import (
	"fmt"
	"sort"

	"go.chromium.org/tast-tests/cros/local/chrome"
	"go.chromium.org/tast/core/testing"
)

type featureType uint32
type featureComboType uint32

// comb creates the feature combination from features.
func comb(features ...featureType) featureComboType {
	var featureComb featureComboType = 0
	for _, f := range features {
		featureComb = featureComboType(uint32(featureComb) | uint32(f))
	}
	return featureComb
}

// add adds feature to featureCombo and returns the feature combination.
func add(featureCombo featureComboType, feature featureType) featureComboType {
	return featureComboType(uint32(featureCombo) | uint32(feature))
}

// remove removes feature from featureCombo and returns the feature combination.
func remove(featureCombo featureComboType, feature featureType) featureComboType {
	return featureComboType(uint32(featureCombo) & ^uint32(feature))
}

// contains returns whether featureCombo has feature.
func contains(featureCombo featureComboType, feature featureType) bool {
	return (uint32(featureCombo) & uint32(feature)) != 0
}

// featureInfo is the name and chrome options for a feature.
type featureInfo struct {
	name    string
	options []chrome.Option
}

// fixtureGenerator is a helper class to generates parameterized features that specifies chrome.Option.
type fixtureGenerator struct {
	// name is the main fixture name which is followed by a name of each fixture
	// param generated by fixtureGenerator. This is to be set in constructing
	// fixtureGenerator.
	name string

	// They are set after constructing.
	// featureMap is the map whose key is a feature and value is featureInfo of
	// the feature and given in initialize().
	featureMap map[featureType]featureInfo
	// featureComboToFixtureName is the map whose key is the feature(s) and
	// value is the entire fixture name. This is filled in getParams().
	featureComboToFixtureName map[featureComboType]string
	// sortedFeatures is the feature slice in the integer order. This is filled
	// in initialize().
	sortedFeatures []featureType
}

// initialize configures following values:
// validFeatureCombos - the valid feature combinations. The fixtures are
// generated from this.
// featureMap - the feature map needs to contain the featureInfo for a feature
// contained in validFeatureCombos.
func (fg *fixtureGenerator) initialize(validFeatureCombos []featureComboType, featureMap map[featureType]featureInfo) {
	var featureList []featureType
	for feature := range featureMap {
		featureList = append(featureList, feature)
	}
	sort.Slice(featureList, func(i, j int) bool { return featureList[i] < featureList[j] })

	featureComboToFixtureName := make(map[featureComboType]string)
	for _, featureCombo := range validFeatureCombos {
		featureComboToFixtureName[featureCombo] = ""
	}

	fg.featureMap = featureMap
	fg.featureComboToFixtureName = featureComboToFixtureName
	fg.sortedFeatures = featureList
}

// genParams generates fixture parameters and returns them. The name of
// fixtures are computed in this function and they are set to
// featureComboToFixtureName for getFixture().
func (fg *fixtureGenerator) genParams() (params []testing.FixtureParam) {
	for featureCombo := range fg.featureComboToFixtureName {
		param := fg.makeParam(featureCombo)
		fixtureName := fg.name
		if param.Name != "" {
			fixtureName += "." + param.Name
		}
		fg.featureComboToFixtureName[featureCombo] = fixtureName
		params = append(params, param)
	}
	return params
}

// makeParam creates the testing.FixtureParam for featureCombo.
func (fg *fixtureGenerator) makeParam(featureCombo featureComboType) testing.FixtureParam {
	var fixtureName string
	var options []chrome.Option
	for _, feature := range fg.sortedFeatures {
		if contains(featureCombo, feature) {
			info := fg.featureMap[feature]
			fixtureName += info.name
			options = append(options, info.options...)
		}
	}
	return testing.FixtureParam{
		Name: fixtureName,
		Val:  options,
	}
}

// printFeatureCombo returns a name of the given feature combination with an
// invalid feature if there is.
func (fg *fixtureGenerator) printFeatureCombo(featureCombo featureComboType) string {
	var comboStr string
	invalidFeatures := featureCombo
	for _, feature := range fg.sortedFeatures {
		if contains(featureCombo, feature) {
			info := fg.featureMap[feature]
			comboStr += info.name
		}
		// Remove feature bit
		invalidFeatures = remove(invalidFeatures, feature)
	}
	if invalidFeatures != 0 {
		return fmt.Sprintf("feature combo (=%s, %d, %b) has invalid bit: %b", comboStr, featureCombo, featureCombo, invalidFeatures)
	}
	return comboStr
}

// checkFeatureCombo causes panic if the given feature combination is not valid.
func (fg *fixtureGenerator) checkFeatureCombo(featureCombo featureComboType) {
	if _, found := fg.featureComboToFixtureName[featureCombo]; !found {
		panic(fmt.Sprintf("Invalid feature Combo: %s (fixture generator name = %s, value = %b, %v)", fg.printFeatureCombo(featureCombo), fg.name, featureCombo, fg.featureComboToFixtureName))
	}
}

// getFixture returns the entire fixture name for the given feature combination.
func (fg *fixtureGenerator) getFixture(featureCombo featureComboType) string {
	fg.checkFeatureCombo(featureCombo)
	return fg.featureComboToFixtureName[featureCombo]
}
