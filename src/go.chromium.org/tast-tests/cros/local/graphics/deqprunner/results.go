// Package deqprunner provides functions operating deqp-runner related binaries.
package deqprunner

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"go.chromium.org/tast-tests/cros/local/graphics"
	"go.chromium.org/tast/core/errors"
	"go.chromium.org/tast/core/fsutil"
)

// Result is the parsed result of the deqprunner.
type Result struct {
	Failures []string // List of tests that failed.
	Summary  string   // A short summary of the failures.
}

// PostProcess runs additional trimming to the result directory of the deqp-runner results.
func PostProcess(ctx context.Context, resultDir string) error {
	entries, err := os.ReadDir(resultDir)
	if err != nil {
		return errors.Wrapf(err, "fails to list %v", resultDir)
	}
	includeCSS := false
	for _, e := range entries {
		if e.IsDir() {
			continue
		}
		// Remove the large (~15Mb) temporary .shader_cache files generated by the dEQP runs, so we don't upload them with the logs.
		if strings.HasSuffix(e.Name(), ".shader_cache") {
			if err := os.RemoveAll(filepath.Join(resultDir, e.Name())); err != nil {
				return errors.Wrap(err, "failed to remove shader_cache")
			}
		}
		if strings.HasSuffix(e.Name(), ".xml") {
			includeCSS = true
		}
	}

	// If we have any QPA XML files, then we'll want to include the CSS
	// in the logs so you can view them.
	if includeCSS {
		stylesheetDir := filepath.Join(graphics.DEQPBaseDir, "testlog-stylesheet")
		for _, file := range []string{"testlog.css", "testlog.xsl"} {
			if err := fsutil.CopyFile(filepath.Join(stylesheetDir, file), resultDir); err != nil {
				return errors.Wrapf(err, "failed to copy %v", file)
			}
		}
	}
	return nil
}

// Parse parse the failures.csv and returns the parsed Result.
func Parse(resultDir string) (Result, error) {
	result := Result{}
	out, err := os.ReadFile(filepath.Join(resultDir, "failures.csv"))
	if err != nil {
		return result, errors.Wrap(err, "failed to read failures.csv")
	}
	result.Failures = strings.Split(strings.TrimSpace(string(out)), "\n")
	sort.Strings(result.Failures)

	if len(result.Failures) == 0 {
		return result, errors.New("no failures in failures.csv")
	} else if len(result.Failures) == 1 {
		result.Summary = fmt.Sprintf("Failed test: %v", result.Failures[0])
		return result, nil
	} else if len(result.Failures) == 2 {
		result.Summary = fmt.Sprintf("Failed tests: %v", result.Failures)
		return result, nil
	}
	// 3+ failures.
	// We tried to count how many failures in first layer of deqp components. e.g. `3 tests in dEQP-VK.api, 16 tests in dEQP-VK.memory`
	counter := make(map[string]int)
	for _, test := range result.Failures {
		components := strings.Split(test, ".")
		prefix := strings.Join(components[:2], ".")
		counter[prefix]++
	}
	// Sort the keys so we have stable results.
	var keys []string
	for k := range counter {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var summary []string
	for _, k := range keys {
		summary = append(summary, fmt.Sprintf("%v failures in %v", counter[k], k))
	}
	result.Summary = strings.Join(summary, ", ") + " (see failures.csv)"
	return result, nil
}
