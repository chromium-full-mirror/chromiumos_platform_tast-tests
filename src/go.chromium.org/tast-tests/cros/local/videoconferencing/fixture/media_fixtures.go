func mediaSetupFixture(camConfig cameraConfig) testing.FixtureImpl {
	return &mediaFixtureImpl{camConfig: camConfig}
}

func mediaSetupFixtureNoScreenRecorder(camConfig cameraConfig) testing.FixtureImpl {
	return &mediaFixtureImpl{camConfig: camConfig, disableScreenRecorder: true}
}

// mediaFixtureImpl implements testing.FixtureImpl.
type mediaFixtureImpl struct {
	camConfig             cameraConfig
	cleanup               []action.Action // A list of cleanup actions to be executed in teardown.
	cr                    *chrome.Chrome
	tconn                 *chrome.TestConn
	recorder              *uiauto.ScreenRecorder
	disableScreenRecorder bool
}

// FixtData is the data returned by SetUp and passed to tests.
type FixtData struct {
	cr *chrome.Chrome
	bt browser.Type
	// ARC enables interaction with an already-started ARC environment.
	// It cannot be closed by tests.
	arc *arc.ARC
	// UIDevice is a UI Automator device object.
	// It cannot be closed by tests.
	dev *ui.Device
}

// Chrome returns Chrome. This adds support for chrome.HasChrome interface.
func (fd FixtData) Chrome() *chrome.Chrome {
	return fd.cr
}

// BrowserType returns the browser type setup in fixture. This adds support for
// browser.HasBrowserType interface.
func (fd FixtData) BrowserType() browser.Type {
	return fd.bt
}

// ARC returns the ARC instance setup in fixture.
func (fd FixtData) ARC() *arc.ARC {
	return fd.arc
}

// UIDevice returns ARC UI Automator device object setup in fixture.
func (fd FixtData) UIDevice() *ui.Device {
	return fd.dev
}

func (f *mediaFixtureImpl) SetUp(ctx context.Context, s *testing.FixtState) interface{} {
	var fixtData FixtData
	parentVal := s.ParentValue()

	switch parentVal.(type) {
	case *baseSetupFixtData:
		f.cr = parentVal.(*baseSetupFixtData).cr
		fixtData = FixtData{
			cr: f.cr,
			bt: parentVal.(*baseSetupFixtData).bt,
		}
	case *arc.PreData:
		f.cr = parentVal.(*arc.PreData).Chrome
		fixtData = FixtData{
			cr:  f.cr,
			bt:  browser.TypeAsh,
			arc: parentVal.(*arc.PreData).ARC,
			dev: parentVal.(*arc.PreData).UIDevice,
		}
	default:
		s.Fatalf("Base fixture %T is not supported", parentVal)
	}

	if f.cr.LoginMode() != "NoLogin" {
		// cr.TestAPIConn does not work on login page.
		// It can be achieved via cr.SigninProfileTestAPIConn(ctx) but not necessary.
		tconn, err := f.cr.TestAPIConn(ctx)
		if err != nil {
			s.Fatal("Failed to get test API connection: ", err)
		}
		f.tconn = tconn

		// Set shelf to never hide to force show shelf.
		dispInfo, err := display.GetPrimaryInfo(ctx, f.tconn)
		if err != nil {
			s.Fatal("Failed to get primary display info: ", err)
		}

		if err := ash.SetShelfBehavior(ctx, f.tconn, dispInfo.ID, ash.ShelfBehaviorNeverAutoHide); err != nil {
			s.Fatal(`Failed to set shelf behavior to "never hidden": `, err)
		}
	}

	f.cleanup = []action.Action{}

	if f.camConfig.fakeCameraInput != "" {
		// Fake image input must be placed under camera cache folder,
		// which is a sandbox environment for camera testing.
		fakeFilePath := cameraCacheFolder + f.camConfig.fakeCameraInput
		if err := fsutil.CopyFile(s.DataPath(f.camConfig.fakeCameraInput), fakeFilePath); err != nil {
			s.Fatal("Failed to copy fake camera input: ", err)
		}

		f.cleanup = append(f.cleanup, func(ctx context.Context) error {
			return os.Remove(fakeFilePath)
		})
	}

	// Setup camera.
	testing.ContextLogf(ctx, "Setting up camera: %+v", f.camConfig)
	if err := f.setupCamera(ctx); err != nil {
		s.Fatal("Failed to setup camera: ", err)
	}

	return fixtData
}

func (f *mediaFixtureImpl) PreTest(ctx context.Context, s *testing.FixtTestState) {
	// Do not setup recorder if f.tconn is not created.
	if f.tconn == nil {
		return
	}

	if !f.disableScreenRecorder {
		f.recorder = uiauto.CreateAndStartScreenRecorderWithAutoSelect(ctx, f.tconn)
	}

	// Clean up lacros browser b:324957897
	isAppRunning, err := ash.AppRunning(ctx, f.tconn, apps.Lacros.ID)
	if err != nil {
		s.Logf("Failed to check app %s running", apps.Lacros.ID)
	}

	if isAppRunning {
		apps.Close(ctx, f.tconn, apps.Lacros.ID)
	}
}

func (f *mediaFixtureImpl) PostTest(ctx context.Context, s *testing.FixtTestState) {
	// Do nothing if the recorder is not initialized.
	if f.recorder != nil {
		f.recorder.StopAndSaveOnError(ctx, filepath.Join(s.OutDir(), "record.webm"), s.HasError)
	}
}

func (f *mediaFixtureImpl) Reset(ctx context.Context) error {
	return nil
}

func (f *mediaFixtureImpl) TearDown(ctx context.Context, s *testing.FixtState) {
	for _, cleanupFunc := range f.cleanup {
		if err := cleanupFunc(ctx); err != nil {
			s.Error("Failed to cleanup: ", err)
		}
	}
}

func (f *mediaFixtureImpl) setupCamera(ctx context.Context) error {
	// This ensures always restart cros-camera in the end of cleanup camera settings.
	defer func() {
		f.cleanup = append(f.cleanup, func(ctx context.Context) error {
			return upstart.RestartJob(ctx, "cros-camera")
		})
	}()

	if err := f.togglePlatformEffects(ctx, f.camConfig.platformEffect); err != nil {
		return errors.Wrapf(err, "failed to set platform effects: %v", f.camConfig.platformEffect)
	}

	if err := testutil.SetupTestConfig(ctx, f.camConfig.cameraType); err != nil {
		return errors.Wrap(err, "failed to setup camera test config")
	}
	f.cleanup = append(f.cleanup, testutil.RemoveTestConfig)

	if f.camConfig.cameraType == testutil.UseFakeHALCamera {
		fakeCameraConfig := testutil.FakeCameraConfig{
			ID:        1,
			Connected: true,
		}

		if f.camConfig.fakeCameraInput != "" {
			fakeCameraConfig.Frames = &testutil.FakeCameraImageConfig{
				Path: cameraCacheFolder + f.camConfig.fakeCameraInput,
			}
			fakeCameraConfig.SupportedFormats = []*testutil.FakeCameraFormatsConfig{&testutil.FakeCameraFormatsConfig{
				Width:      1280,
				Height:     720,
				FrameRates: []int{30}}, &testutil.FakeCameraFormatsConfig{
				Width:      1920,
				Height:     1080,
				FrameRates: []int{30}},
			}
		}

		fakeHALConfig := testutil.FakeHALConfig{
			Cameras: []testutil.FakeCameraConfig{fakeCameraConfig},
		}

		if err := testutil.WriteFakeHALConfig(ctx, fakeHALConfig); err != nil {
			return errors.Wrap(err, "failed to configure HAL camera")
		}
		f.cleanup = append(f.cleanup, testutil.RemoveFakeHALConfig)
	}
	const job = "cros-camera"
	if err := upstart.RestartJob(ctx, job); err != nil {
		return errors.Wrap(err, "failed to restart cros-camera after setup camera")
	}
	if err := upstart.WaitForJobStatus(ctx, job, upstartcommon.StartGoal, upstartcommon.RunningState, upstart.RejectWrongGoal, ctxutil.MaxTimeout); err != nil {
		return errors.Wrapf(err, "failed to wait for %v to start running", job)
	}
	return nil
}

// togglePlatformEffects ensures the switch file exists / gone.
// According to the setting requirement, it creates / removes config file.
// Then append restore function to the fixture cleanup.
func (f *mediaFixtureImpl) togglePlatformEffects(ctx context.Context, platformEffect platformEffectLevel) error {
	ensureFileExists := func(ctx context.Context, filePath string) error {
		if _, err := os.Stat(filePath); os.IsNotExist(err) {
			file, err := os.Create(filePath)
			if err != nil {
				return errors.Wrapf(err, "failed to create %q", filePath)
			}
			file.Close()
			f.cleanup = append(f.cleanup, func(ctx context.Context) error {
				if err := os.Remove(filePath); err != nil && !os.IsNotExist(err) {
					return errors.Wrapf(err, "failed to remove %q", filePath)
				}
				return nil
			})
		} else if err != nil {
			return errors.Wrapf(err, "failed to check %q", filePath)
		}
		return nil
	}

	ensureFileGone := func(ctx context.Context, filePath string) error {
		if err := os.Remove(filePath); err == nil {
			// Switch file should be restored in cleanup if it is removed.
			f.cleanup = append(f.cleanup, func(ctx context.Context) error {
				file, err := os.Create(filePath)
				if err != nil {
					return errors.Wrapf(err, "failed to create %q", filePath)
				}
				file.Close()
				return nil
			})
		} else if !os.IsNotExist(err) {
			return errors.Wrapf(err, "failed to remove %q", filePath)
		}
		return nil
	}

	switch f.camConfig.platformEffect {
	// platformEffectsForceEnablePath: Yes; platformEffectsForceDisablePath: No
	case platformEffectEnabled:
		if err := ensureFileGone(ctx, platformEffectsForceDisablePath); err != nil {
			return err
		}
		return ensureFileExists(ctx, platformEffectsForceEnablePath)

	// platformEffectsForceEnablePath: No; platformEffectsForceDisablePath: Yes
	case platformEffectDisabled:
		if err := ensureFileGone(ctx, platformEffectsForceEnablePath); err != nil {
			return err
		}
		return ensureFileExists(ctx, platformEffectsForceDisablePath)

	// platformEffectsForceEnablePath: No; platformEffectsForceDisablePath: No
	default:
		if err := ensureFileGone(ctx, platformEffectsForceEnablePath); err != nil {
			return err
		}
		return ensureFileGone(ctx, platformEffectsForceDisablePath)
	}
}

// FakeCameraHALFixture returns a fake Camera HAL fixture implementation with customized configuration.
func FakeCameraHALFixture(enabledPlatformEffect bool, fakeInputFile string) testing.FixtureImpl {
	camConfig := cameraConfig{
		cameraType:      testutil.UseFakeHALCamera,
		platformEffect:  platformEffectEnabled,
		fakeCameraInput: fakeInputFile,
	}

	if !enabledPlatformEffect {
		camConfig.platformEffect = platformEffectDisabled
	}

	return mediaSetupFixture(camConfig)
}
